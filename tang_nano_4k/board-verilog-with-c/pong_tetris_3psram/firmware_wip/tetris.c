/* 一个音符 = 半周期滴答数（0 表示休止）+ 持续滴答数 */
typedef struct { uint16_t half; uint16_t ticks; } Note;   /* 音符类型：half 是半周期（决定音高），ticks 是持续多少个滴答 */

/* 音准全靠半周期这一步决定，所以这里是四舍五入的：之前直接向下取整才把
   G5 算成了 833 Hz 而不是 784。时长按 SND_BPM 的十六分之一拍来数，这样
   曲子能保持自己的节奏而不跑偏——若按每种音符固定多少毫秒就会漂。 */
#define SND_BPM     140   /* 背景音乐的拍速：每分钟 140 拍 */
