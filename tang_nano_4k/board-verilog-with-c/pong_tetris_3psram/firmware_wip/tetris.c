static int cells_valid(int px, int py, const Cell c[4])   /* 判断把方块放到 px,py 会不会撞墙或撞到别的方块 */
{   /* 函数体开始 */
    int i;   /* 循环下标 */
    for (i = 0; i < 4; i++) {   /* 方块的四个格子逐个检查 */
        int bx = px + c[i].x, by = py + c[i].y;   /* 算出这个格子在棋盘上的位置 */
        if (bx < 0 || bx >= COLS || by >= ROWS) return 0;   /* 出界，也就是左右越界或掉出底部，就不合法 */
        if (by >= 0 && board[by][bx]) return 0;   /* 如果压在已经落定的方块上，也不合法 */
    }   /* 遍历结束 */
    return 1;   /* 全部合法，返回 1 */
}   /* 函数结束 */

/* 三个实时数值各占一行，所以每一个都是单独标记的：一次硬降只会动 SCORE，
   一次消行只会动 LINES（而 LEVEL 只在真的升级时才动）；以前把另外两行也一起
   重画，代价是"真正变了的那一行"的六倍格子量。

   这几个函数还顺便重新格式化那三个数值字符串，所以数字转换是"每次变化做一次"，
   而不是"每个被重画的像素做一次"。 */
static void mark_score_dirty(void)   /* 分数变了：刷新数值并标记分数那一行要重画 */
{   /* 函数体开始 */
    refresh_values();   /* 重新格式化三个数值字符串 */
    mark_dirty_slot(DS_SCORE, SVX, SVY, SVX + VAL_W - 1, SVY + VAL_H - 1);   /* 标记分数数值所在的那个矩形 */
}   /* 函数结束 */

static void mark_level_dirty(void)   /* 等级变了：标记等级那一行要重画 */
{   /* 函数体开始 */
    refresh_values();   /* 重新格式化数值 */
    mark_dirty_slot(DS_LEVEL, LVX, LVY, LVX + VAL_W - 1, LVY + VAL_H - 1);   /* 标记等级数值所在的矩形 */
}   /* 函数结束 */

static void mark_lines_dirty(void)   /* 行数变了：标记行数那一行要重画 */
{   /* 函数体开始 */
    refresh_values();   /* 重新格式化数值 */
    mark_dirty_slot(DS_LINES, IVX, IVY, IVX + VAL_W - 1, IVY + VAL_H - 1);   /* 标记行数数值所在的矩形 */
}   /* 函数结束 */

/* NEXT 条变了 → 只重画方块真正可能画到的那几行。内部有 18 行高，但每个方块都
   按初始朝向（旋转 0）画，最高两个格子（14 行），而且是居中的——所以只有
   NY0+PB+2 .. NY0+NH-PB-3 这几行会真正带颜色，把 18 行全标上，会在每一个
   方块身上都多花约 10 格。 */
#define NINY0           (NY0 + PB + 2)   /* NEXT 条里方块可能画到的第一行 */
#define NINY1           (NY0 + NH - PB - 3)   /* NEXT 条里方块可能画到的最后一行 */

static int next_pend;   /* NEXT 条要重画，但先压一帧：它不着急，别和硬降/HOLD 抢同一个帧 */

static void mark_next_dirty(void)   /* NEXT 队列变了：先记账，等下一帧再真正标脏 */
{   /* 函数体开始 */
    next_pend = 1;   /* 只记一个"待办"，把这块重画让到下一帧去做 */
}   /* 函数结束 */

static void next_flush(void)   /* 把压了一帧的 NEXT 重画真正标上去（在主循环帧首调用） */
{   /* 函数体开始 */
    if (!next_pend) return;   /* 没有待办就什么都不用做 */
    next_pend = 0;   /* 清掉待办，免得重复重画 */
    mark_dirty_slot(DS_PANEL, NX0 + PB, NINY0, NX0 + NW - PB - 1, NINY1);   /* 真正标出 NEXT 条内部那块 */
}   /* 函数结束 */

/* HOLD 槽变了 → 它的内部必须重画 */
static void mark_hold_dirty(void)   /* HOLD 槽变了：标记它的内部要重画 */
{   /* 函数体开始 */
    mark_dirty_slot(DS_HOLD, HX0 + PB, HY0 + PB,   /* 标进 HOLD 专用的槽，不和 NEXT 条挤在一起 */
                    HX0 + HW - PB - 1, HY0 + HH - PB - 1);   /* 一直到右下角 */
}   /* 函数结束 */

static int grav_frames(void);          /* 定义在下面；新方块出生时会用到 */

/* 把类型为 t 的方块放到顶部中间那个出生位置并让它开始下落。
   队列出生和 HOLD 把方块重新放回场上，都共用这个函数。 */
static void place_piece(int t)   /* 把类型为 t 的方块放到顶部中间，开始下落 */
{   /* 函数体开始 */
    cur_type = t;   /* 设置当前方块类型 */
    cur_rot = 0;   /* 旋转次数归零，也就是初始朝向 */
    cur_y = 0;   /* 从最顶上一行开始 */
    piece_cells(cur_type, cur_rot, cur_cells);   /* 算出它的 4 个格子坐标 */

    /* 按方块自己的外接框来居中，这样每种形状在最顶上都会出现在场地正中间、
       而不是固定某一列——外接框本身也在这里设好，它就是 game_pixel() 里逐像素
       判断用来排除、以及 piece_sync() 用来重画的那个框。 */
    set_cells(cur_cells);   /* 装入格子并顺手更新外接框 */
    cur_x = (COLS - (pmax_x + 1)) / 2;   /* 横向居中，让方块出现在场地正中间 */

    /* 预先把下落计时器充好，这样新方块在屏幕上出现的第一帧就往下走一格，
       而不用先干等满一个下落周期。 */
    grav_cnt = grav_frames() - 1;   /* 把下落计时器预充好，让新方块第一帧就往下掉一格 */
    if (!cells_valid(cur_x, cur_y, cur_cells)) {   /* 如果出生位置就被占住了，说明顶到天花板了 */
        game_over = 1;   /* 标记游戏结束 */
        sound_over();              /* 音乐切换成游戏结束主题曲 */
        /* 开始进入游戏结束画面：那几个字在这一帧就亮起来，而 ban_state 预先设成
           主循环下一帧会算出来的值（go_shown 为 1、第一阶段），这样那一帧就不会
           把同一块区域再重画一遍。 */
        go_phase  = 0;   /* 横幅从第一阶段，也就是 GAME OVER 字样开始 */
        go_frames = 0;   /* 结束画面已经过的帧数清零 */
        blink_cnt = 0;   /* 闪烁计数器清零 */
        go_shown  = 1;   /* 横幅立刻亮起来 */
        ban_state = 1;   /* 预置横幅状态为「亮着、第一阶段」 */
        mark_dirty_slot(DS_BANNER, BAN_X, BAN_Y,   /* 标记横幅区域要重画 */
                        BAN_X + BAN_W - 1, BAN_Y + BAN_H - 1);   /* 一直到横幅右下角 */
    }   /* 判断结束 */
}   /* 函数结束 */

/* 从队列里取出下一个方块。这是唯一一处清除"每个方块只能用一次 HOLD"这个限制的
   地方——和参照的固件完全一样，所以刚从 HOLD 槽里拿出来的那个方块不能再立刻
   被 HOLD 回去。 */
static void spawn(void)   /* 从队列取出下一个方块，正式让它上场 */
{   /* 函数体开始 */
    int t = nextq[0];   /* 取出队首的方块类型 */

    nextq[0] = nextq[1];   /* 队列往前挪一格 */
    nextq[1] = nextq[2];   /* 第二格变第一格 */
    nextq[2] = rnd7();   /* 队尾补一个新的随机方块 */
    refresh_next();                    /* 重新算好那三个烤制方块的位置 */
    mark_next_dirty();                 /* NEXT 条是烤好的，所以队列一挪就要重画它 */

    place_piece(t);   /* 把取出的这个方块放上场 */
    hold_used = 0;   /* 复位 HOLD 限制，新方块可以再用一次 HOLD */
}   /* 函数结束 */

/* ------------------------------------------------------------------ */
/* 开新一局时的状态复位。                                              */
/* ------------------------------------------------------------------ */
static void init_game(void)   /* 新开一局：把所有游戏状态复位 */
{   /* 函数体开始 */
    int r, c, i;   /* 行、列和通用下标 */
    for (r = 0; r < ROWS; r++)   /* 逐行处理 */
        for (c = 0; c < COLS; c++)   /* 每行逐列处理 */
            board[r][c] = 0;   /* 把棋盘这一格清空，0 表示空 */
    game_over = 0;   /* 清除游戏结束标记 */
    paused = 0;   /* 取消暂停 */
    go_shown = 0;                      /* 新开的棋盘上不带横幅 */
    go_phase = 0;                      /* 而且从"字样"那一阶段开始，不是从提示语 */
    go_frames = 0;   /* 结束画面已经过的帧数清零 */
    ban_state = -1;                    /* 重画完之后横幅那一带什么都还没画，所以
                                          下次顶到天花板时会把它从头重画一遍 */
    ghost_on = 0;                      /* 新棋盘一画完，缓冲区里就不剩旧残影的东西了
                                          ——见重启时那次重画 */
    gbx1 = -1;   /* 让残影记住的旧框失效，下次必定重画 */
    gbt = -1;   /* 残影记住的形状也失效 */
    pcb1 = -1;                         /* 以及旧方块那个烤好的外接框也失效 */
    pbt = -1;   /* 方块记住的形状失效 */
    grav_cnt = das_dir = das_cnt = 0;   /* 下落计时、连发方向、连发倒数全部清零 */
    score = 0;   /* 分数归零 */
    lines_cleared = 0;   /* 消行数归零 */
    level = 0;   /* 等级归零 */
    hold_type = -1;   /* HOLD 槽清空 */
    hold_used = 0;   /* HOLD 限制复位 */
    refresh_values();                  /* 把三个数值重新格式化成全新的 0 / 0 / 0 */
    for (i = 0; i < 3; i++) dirty[i].pend = 0;   /* 三个显示缓冲区的待重画标记清零 */
    for (i = 0; i < 3; i++) nextq[i] = rnd7();   /* 给 NEXT 队列填满随机的方块 */
    spawn();   /* 生成第一个方块，开局 */
}   /* 函数结束 */

static int try_move(int dx, int dy)   /* 试着把方块移动 dx,dy，成功返回 1 */
{   /* 函数体开始 */
    if (cells_valid(cur_x + dx, cur_y + dy, cur_cells)) {   /* 如果移过去不会撞墙也不会撞块 */
        cur_x += dx; cur_y += dy;   /* 就真的挪过去 */
        return 1;   /* 返回成功 */
    }   /* 判断结束 */
    return 0;   /* 撞了，移动失败返回 0 */
}   /* 函数结束 */

/* dir 为 +1 表示顺时针，-1 表示逆时针。 */
static void do_rotate(int dir)   /* 旋转方块，dir 等于 +1 是顺时针、-1 是逆时针 */
{   /* 函数体开始 */
    Cell nc[4];   /* 暂存旋转后的格子 */
    int nr = (cur_rot + (dir > 0 ? 1 : 3)) & 3;   /* 算新的旋转次数，逆时针等于加 3 再对 4 取余 */
    piece_cells(cur_type, nr, nc);   /* 算出旋转后的 4 个格子 */
    if (cells_valid(cur_x, cur_y, nc)) {   /* 如果转过去不会撞 */
        set_cells(nc);                 /* 格子和它们的外接框要一起更新，绝不能只更新一个 */
        cur_rot = nr;   /* 正式采用新的旋转状态 */
    }   /* 判断结束 */
}   /* 函数结束 */

/* 一次消掉 1..4 行分别得多少基础分（最后还要乘以等级加一） */
static const uint16_t line_score[5] = { 0, 100, 300, 500, 800 };   /* 一次消掉 0 到 4 行分别得多少分 */

static void lock_piece(void)   /* 方块落定：写进棋盘、消掉整行、加分 */
{   /* 函数体开始 */
    int i, r, c, cleared = 0, maxrow = 0, minrow = ROWS;   /* 循环变量、消掉的行数、方块纵向范围 */
    int mincol = COLS, maxcol = 0;   /* 方块横向范围 */
    int top = ROWS, last_clear = -1, bottom;   /* 场上最高方块所在行、最后消掉的行、以及重画范围的底边 */

    for (i = 0; i < 4; i++) {   /* 把方块的四个格子逐个处理 */
        int bx = cur_x + cur_cells[i].x;   /* 算出它所在的棋盘列 */
        int by = cur_y + cur_cells[i].y;   /* 棋盘行 */
        board[by][bx] = (uint8_t)(PIECE_BASE + cur_type);   /* 写进棋盘，存的是调色板基址加类型 */
        if (by > maxrow) maxrow = by;   /* 更新方块最下行 */
        if (by < minrow) minrow = by;   /* 更新最上行 */
        if (bx > maxcol) maxcol = bx;   /* 更新最右列 */
        if (bx < mincol) mincol = bx;   /* 更新最左列 */
    }   /* 遍历结束 */

    /* 挪动之前，最靠上的那一行有方块的行：它上面的行挪动前后都是纯场地底色，
       所以永远不需要重画 */
    for (r = 0; r < ROWS; r++) {   /* 从上往下找第一行有方块的行 */
        for (c = 0; c < COLS; c++) if (board[r][c]) break;   /* 逐列看，遇到非空就停 */
        if (c < COLS) { top = r; break; }   /* 找到就记下这一行并跳出 */
    }   /* 查找结束 */

    /* 把每一行满的都消掉，上方的所有东西整体往下挪一行 */
    for (r = ROWS - 1; r >= 0; ) {   /* 从最底行往上检查每一行是否满 */
        int full = 1;   /* 先假设这一行是满的 */
        for (c = 0; c < COLS; c++) if (!board[r][c]) { full = 0; break; }   /* 只要有一格是空的就判定不满 */
        if (full) {   /* 如果满了就消掉它 */
            int rr;   /* 纵向挪动用的下标 */
            last_clear = r;   /* 记下刚消掉的行号 */
            for (rr = r; rr > 0; rr--)   /* 把这一行上面的所有行 */
                for (c = 0; c < COLS; c++) board[rr][c] = board[rr - 1][c];   /* 整体往下挪一行 */
            for (c = 0; c < COLS; c++) board[0][c] = 0;   /* 最上面空出来的那一行清空 */
            cleared++;   /* 消行数加一 */
        } else {   /* 否则这一行没满 */
            r--;   /* 那就往上检查下一行 */
        }   /* 判断结束 */
    }   /* 循环结束 */

    /* 没消行 → 只有方块自己那几个格子变了，所以只重画它的外接框（约 1~4 格）。
       如果消了行，只有"挪动之前最靠上的那个方块"到"被消掉的最低那一行"之间的
       行可能不一样。分数／行数／等级也只在消行时才动。 */
    if (cleared == 0) {   /* 如果没消掉任何行 */
        mark_dirty(X0 + mincol * CELLX,             Y0 + minrow * CELLY,   /* 只需重画方块自己那块包围框 */
                   X0 + (maxcol + 1) * CELLX - 1,   Y0 + (maxrow + 1) * CELLY - 1);   /* 一直到包围框右下角 */
    } else {   /* 否则有行被消掉 */
        bottom = (last_clear > maxrow) ? last_clear : maxrow;   /* 重画范围的底边取「方块底行」和「消掉的行」里较大的那个 */
        mark_dirty(X0, Y0 + top * CELLY,   /* 从场地最左、到最高方块所在行开始 */
                   X0 + COLS * CELLX - 1,           Y0 + (bottom + 1) * CELLY - 1);   /* 一直到右下角，整片重画 */
        sound_fx(fx_line, FXL_N);   /* 放滑音；背景音乐暂时让位 */

        score        += (uint32_t)line_score[cleared] * (uint32_t)(level + 1);   /* 加分：消行基础分乘以等级加一 */
        if (score > 999999u) score = 999999u;   /* 分数封顶到 999999 */
        lines_cleared += cleared;   /* 累计消行数增加 */
        {   /* 开始处理等级 */
            int lv0 = level;   /* 记下旧等级 */
            level = lines_cleared / LINES_PER_LEVEL;   /* 按每 3 行升一级算出新等级 */
            if (level != lv0) {                 /* 只有真的升级了才处理 */
                mark_level_dirty();   /* 等级变了，标记等级那一行重画 */
                /* 升级的叮声，排在上面那串滑音一结束就响，绝不压在它上面 */
                sound_fx_after(fx_level, LVL_N);   /* 把升级的叮声排到滑音结束后紧接着播 */
            }   /* 等级变化判断结束 */
        }   /* 等级处理结束 */
        mark_score_dirty();   /* 标记分数那一行重画 */
        mark_lines_dirty();   /* 标记行数那一行重画 */
    }   /* 消行分支结束 */

    /* 方块一落定，就在同一帧里把下一个方块放上场——不再压后一帧。
       以前压后那一帧有个很坑的副作用：那一帧里 press_edge 处理的还是"已经
       落定的那块旧方块"，玩家在方块刚出现时按的硬降／HOLD 全打在旧方块身上
       （硬降对它算出来 d=0，于是又调一次 lock_piece，出生反而再被推后一帧）。
       表现出来就是"方块出现以后，头两行按什么都没反应"。
       现在同一帧就换上新方块：按键永远作用在玩家正看着的那一块上，也少等
       一整帧。多出来的那一帧绘制量由 merge_dirty() 和绘制预算兜住——NEXT
       条本来就是压后一帧画的。 */
    spawn();   /* 立刻生成下一个方块（顶出天花板时它会自己切到结束画面） */
}   /* 函数结束 */

/* 等级越高下落越快，最快到每帧掉一行 */
static int grav_frames(void)   /* 算出当前等级下一次下落要等多少帧，等级越高越快 */
{   /* 函数体开始 */
    int g = GRAV_FRAMES - level;   /* 基础间隔减去等级 */
    return (g < 1) ? 1 : g;   /* 至少每帧掉一行，不能再快 */
}   /* 函数结束 */

/* K6 = HOLD。把正在下落的方块和 HOLD 槽里的方块互换；每个方块只能用一次
   （hold_used 只在 spawn() 里被清除）。如果槽是空的，就把当前方块存进去，
   改成让队列里的下一个方块上场。 */
static void do_hold(void)   /* HOLD 操作：把当前方块和存起来的那块交换 */
{   /* 函数体开始 */
    int t;   /* 临时变量 */

    if (hold_used) return;   /* 这一块已经用过 HOLD 了，直接返回 */

    if (hold_type < 0) {                 /* 槽是空的：存进去，再从队列取下一个 */
        hold_type = cur_type;   /* 把当前方块存进 HOLD 槽 */
        refresh_hold();   /* 重算 HOLD 槽的显示缓存 */
        mark_hold_dirty();   /* 标记 HOLD 框要重画 */
        spawn();                         /* 这一句会把 hold_used 清掉…… */
        hold_used = 1;                   /* ……但这个方块现在已经 HOLD 过了，马上设回去 */
        return;   /* 结束 */
    }   /* 判断结束 */

    t = hold_type;                       /* 真正地互换：先取出槽里那块 */
    hold_type = cur_type;   /* 再把当前方块放进 HOLD 槽 */
    refresh_hold();   /* 重算显示缓存 */
    mark_hold_dirty();   /* 标记 HOLD 框重画 */
    place_piece(t);   /* 把原来存的那块放上场 */
    hold_used = 1;   /* 标记这一块已经用过 HOLD */
}   /* 函数结束 */

/* K5 = 硬降：让方块一口气直直砸到它的落点行，每砸一行加 2 分（和参照固件
   一样），然后让它落定。 */
static void do_hard_drop(void)   /* 硬降：方块一口气砸到最底，加分然后落定 */
{   /* 函数体开始 */
    int d = 0;   /* 已经往下砸了几行 */

    while (cells_valid(cur_x, cur_y + d + 1, cur_cells)) d++;   /* 一直往下试，直到再下一格就会撞 */
    cur_y += d;   /* 把方块挪到最底 */
    if (d > 0) {   /* 如果确实砸下去了 */
        score += (uint32_t)(2 * d);   /* 每砸一行加 2 分 */
        if (score > 999999u) score = 999999u;   /* 分数封顶 */
        mark_score_dirty();   /* 标记分数重画 */
    }   /* 加分判断结束 */
    lock_piece();   /* 让方块落定 */

    /* 这里不再当场 spawn()。硬降这一帧已经要重画"原来位置擦掉 + 落点画上 +
       残影搬家 + 分数"，再塞进"新方块 + 整条 NEXT"就会把这一帧压到超过一个
       显示周期——那样画面反而要多等一帧，手感更慢。新方块仍旧由 spawn_delay
       在下一帧的帧首生成，帧负载被摊开，硬降本身就能准点上屏。 */
}   /* 函数结束 */

/* ------------------------------------------------------------------ */
/* 发布硬件矩形                                                         */
/*                                                                     */
/* 正在下落的方块以前是四个矩形，一个格子一个小方块——现在不能这么画了，  */
/* 因为一个硬件矩形只能填一种纯色，而如今每个格子都带高光。它改成"烤"进   */
/* 帧缓冲，由 piece_sync() 保持同步，而 game_pixel() 把它画成和落定方块  */
/* 一模一样的带高光小格子。                                              */
/*                                                                     */
/* 这样一来，整个正常游戏过程中对象表都是空的——这正是这里完全不用跑在    */
/* 下落路径上的原因。GAME OVER 横幅也是烤好的文字（见 game_pixel），所以  */
/* 只剩一个硬件叠加层：暂停图标，两根朴素的竖条——这正是扁平矩形擅长的     */
/* 东西——压在场地上面，一个字节的帧缓冲流量都不需要。                     */
/* ------------------------------------------------------------------ */

static void publish_sprites(void)   /* 决定这一帧要用硬件矩形画哪些东西，比如暂停图标，或者全关 */
{   /* 函数体开始 */
    if (game_over) {   /* 如果游戏已经结束了 */
        /* 顶到上限那个横幅现在是烤好的文字（见 game_pixel），所以对象表里什么
           都不用放：以前靠矩形 0 闪出来的那根条已经没了，另外四个本来也是关着
           的。 */
        spr_off(0); spr_off(1); spr_off(2); spr_off(3); spr_off(4);   /* 五个硬件矩形全部关掉，因为横幅是直接画进显存的 */
        return;   /* 结束 */
    }   /* 判断结束 */

    if (paused) {   /* 如果游戏暂停了 */
        /* 闪烁的「||」暂停图标：两根竖条，这个形状绝不会和烤好的场地里的
           任何东西混淆 */
        spr_off(2); spr_off(3); spr_off(4);   /* 只留前两个矩形来画图标，其余关掉 */
        if (blink_cnt < 16) {   /* 闪烁的前半周期就显示暂停图标 */
            spr_box(0, 150, 97, 14, 45, IDX_I, 1);   /* 左边那根竖条，给好位置尺寸和颜色 */
            spr_box(1, 170, 97, 14, 45, IDX_I, 1);   /* 右边那根竖条，两根合起来就是「||」暂停符号 */
        } else {   /* 否则闪烁的后半周期 */
            spr_off(0); spr_off(1);   /* 把两根竖条关掉，这样图标就闪起来了 */
        }   /* 判断结束 */
        return;   /* 结束 */
    }   /* 判断结束 */

    /* 正常的一帧不通过对象表画任何东西：方块和两个面板都是烤好的。这两次写
       只是为了确保"从结束画面或暂停切回来的第一帧"里，原本开着的叠加层已经
       关掉了。 */
    spr_off(0);   /* 正常帧：把第 0 个硬件矩形关掉 */
    spr_off(1);   /* 第 1 个也关掉，保证从结束或暂停状态切回来时图标不残留 */
}   /* 函数结束 */

/* ------------------------------------------------------------------ */
/* 残影／落点预览                                                        */
/*                                                                     */
/* 残影是"烤"进帧缓冲的——每个格子一个空心小框——因为面板的五个矩形画不了  */
/* 轮廓，而且其中四个已经被正在下落的方块占用了。                          */
/*                                                                     */
/* 它平时是不花代价的：它的落点行只取决于方块所在的"列"和场上堆叠，而不取  */
/* 决于方块已经下落了多少，所以方块直直往下掉时它是原地不动的，这个函数就    */
/* 什么都不做。只有横向移动、旋转、HOLD 交换、新方块出生或堆叠变化才会让它   */
/* 动——那时候就把它的新旧外接框并成"一个"脏矩形（槽 DS_GHOST），既擦掉旧   */
/* 框、又把新框烤进去。                                                  */
/*                                                                     */
/* 上面这些变化里，凡是让残影关掉、或者让它移动的，都必须把它上次画在哪个  */
/* 框标出来，否则旧框会像幽灵一样留在缓冲区里。                            */
/* ------------------------------------------------------------------ */
static void ghost_sync(void)   /* 让画进显存的落点预览残影跟上当前方块 */
{   /* 函数体开始 */
    int i, mx = 0, my = 0, mn = 9, dy, was = ghost_on;   /* 循环变量、方块外接框、落到底的行、以及原先残影是否开着 */
    int on = 0, x1 = 0, y1 = 0, x2 = 0, y2 = 0;   /* 新的残影开关和它新的像素外接框 */

    if (running && !game_over && !paused) {   /* 游戏正常进行、没结束没暂停 */
        for (i = 0; i < 4; i++) {   /* 看方块的四个格子 */
            if (cur_cells[i].x > mx) mx = cur_cells[i].x;   /* 记下最右的格子 */
            if (cur_cells[i].y > my) my = cur_cells[i].y;   /* 记下最下的格子 */
            if (cur_cells[i].y < mn) mn = cur_cells[i].y;   /* 记下最上的格子 */
        }   /* 遍历结束 */
        dy = cur_y;   /* 从方块当前所在行开始试 */
        while (cells_valid(cur_x, dy + 1, cur_cells)) dy++;   /* 一直往下试，找出它最终会落到哪一行 */
        if (dy > cur_y) {                  /* 已经贴着地面了——那就没什么可显示的 */
            on         = 1;   /* 要显示残影 */
            ghost_row  = dy;   /* 记下落点行 */
            ghost_w    = mx;   /* 记下方块宽度，按格子数算 */
            ghost_h    = my;   /* 记下方块高度 */
            x1 = X0 + cur_x * CELLX;   /* 残影框的左边缘 */
            /* 这个框从方块最上面那行"有颜色"的格开始，而不是从 ghost_row 开始：
               横躺的 I 型方块四个格子都在它的第二行上，如果框总是从 ghost_row
               起算，那每横移一步都会多重画一整行空白——相当于它自己格数的一半。 */
            y1 = Y0 + (dy + mn) * CELLY;   /* 残影框的上边缘，从方块最上面那行亮格的位置算起 */
            /* 残影是按形状"自己的格子"来画的，只是把那些格子的网格带染上色
               （见 game_pixel()）；它最外那圈右／下边缘，用的是紧挨形状外面那
               一格的网格带——也就是它右边那一格的第一"列"、和下面那一格的头两
               行。所以这个框在两个方向上都要多够出去一格、并且要伸进那一格
               （右 1 像素、下 2 像素，也就是场地自己的线宽）：它等于形状的格子
               网格，也就是下落方块和落定方块占据的同一个 9 x 8 的框，再加上
               右边和底部那点外沿。x 方向上多留的 1 像素只是框并不需要的一个
               像素，这样两个方向就能用同一个公式算。（如果有个落定方块紧贴着
               残影，那条边缘会收回到形状自己的格子里，而那本来就在这个框内。） */
            x2 = X0 + (cur_x + mx + 1) * CELLX + 1;   /* 残影框的右边缘，往右多算一格给边框留位置 */
            y2 = Y0 + (dy + my + 1) * CELLY + 1;   /* 残影框的下边缘 */
        }   /* 判断结束 */
    }   /* 外层条件结束 */
    ghost_on = on;   /* 更新残影开关 */

    /* 没变——这是绝大多数情况，也正是方块单纯下落时这个函数不花代价的全部
       原因。判断形状必须用"类型 + 旋转次数"，不能用外接框：同一个方块的两种
       不同旋转可能共用同一个外接框（T 型正着反着都是 3x2），只比框的话，就会
       让旧形状一直烤在帧缓冲里出不来。 */
    if (on && was && cur_type == gbt && cur_rot == gbro &&   /* 如果残影还在、类型和形状都没变 */
        ghost_row == gbrow && cur_x == gbcol)   /* 而且落点行和列也都相同 */
        return;   /* 那就什么都不用做，方块直直往下掉时就是这种常态 */

    /* 擦掉旧框、画上新框。通常只用"一个"矩形——也就是它们的并集：一次横向
       移动（按住键时 DAS 连发每帧都要重画的那种）只会让残影挪一列，两个框
       互相重叠，并集比它们各自大不了多少，代价只有"两个各约 40 格矩形"的
       一半。只有当新旧框既不共享 x 也不共享 y，也就是斜着跳过去时，才拆成
       两个矩形——HOLD 交换有可能把方块落到井的另一侧、高度也不一样。那种情况
       下并集会是横跨场地的约 200 格大框。 */
    {   /* 开始算这一帧要重画哪儿 */
        int near = (x1 <= gbx2 && gbx1 <= x2) || (y1 <= gby2 && gby1 <= y2);   /* 判断新旧框是否挨着，横向或纵向任一边相交就算 */

        if (gbx1 >= 0 && on && near) {   /* 有旧框、残影还在、而且新旧框挨着 */
            int ux1 = (gbx1 < x1) ? gbx1 : x1;   /* 并集左边缘取两者里较小的那个 */
            int uy1 = (gby1 < y1) ? gby1 : y1;   /* 并集上边缘也往小取 */
            int ux2 = (gbx2 > x2) ? gbx2 : x2;   /* 并集右边缘取较大的 */
            int uy2 = (gby2 > y2) ? gby2 : y2;   /* 并集下边缘也往大取 */
            mark_dirty_slot(DS_GHOST, ux1, uy1, ux2, uy2);   /* 一个矩形就同时抹掉旧的、画上新的 */
        } else {   /* 否则新旧框离得远 */
            if (gbx1 >= 0) mark_dirty_slot(DS_GHOST,  gbx1, gby1, gbx2, gby2);   /* 先把旧框标进去，让它被擦掉 */
            if (on)        mark_dirty_slot(DS_GHOST2, x1,   y1,   x2,   y2);   /* 再把新框标进第二个槽，免得拼成一个超大矩形 */
        }   /* 判断结束 */
    }   /* 标记结束 */
    gbx1 = -1;   /* 旧框记录先置为无效 */
    if (!on) { gbt = -1; return; }   /* 如果残影关掉了，形状记录也清掉并返回 */

    gbx1 = x1; gby1 = y1; gbx2 = x2; gby2 = y2;   /* 记下这次画的包围框，留给下次比较用 */
    gbt = cur_type; gbro = cur_rot; gbrow = ghost_row; gbcol = cur_x;   /* 记下这次用的类型、旋转、落点行和列 */
}   /* 函数结束 */

/* ------------------------------------------------------------------ */
/* 正在下落的方块                                                        */
/*                                                                     */
/* 方块现在也是"烤"进帧缓冲的，理由和残影一样：面板矩形只能填一种纯色，而  */
/* 现在每个格子都带高光（见 cell_body()），所以以前那种"发四个小方块矩形"  */
/* 的做法已经行不通了。game_pixel() 把它画成和落定方块完全一样的带高光小   */
/* 格子——这正是"锁定"不花代价的原因：锁定之后那一帧看起来毫无变化，不管   */
/* 一个格子是来自方块还是来自棋盘，所以这里永远只需要重画"方块离开"的那块  */
/* 区域。                                                              */
/*                                                                     */
/* 方块单纯下落时同样不花代价：一次下落只走一行，新旧框互相重叠，并集比它们 */
/* 各自大不了多少。两个方向都重叠的框走同一个矩形（DS_PIECE）；而 HOLD 交换 */
/* 或硬降可能让方块一帧内跨越整个井高，那种新旧框一行都不重叠——并集会是纵贯 */
/* 整块场地的一条细带——所以它们改走第二个槽（DS_PIECE2）。              */
/* ------------------------------------------------------------------ */
static void piece_sync(void)   /* 让画进显存的活动方块跟上它的真实位置 */
{   /* 函数体开始 */
    int on = (running && !game_over) ? 1 : 0;   /* 游戏进行中才需要显示方块 */
    int x1 = 0, y1 = 0, x2 = 0, y2 = 0;   /* 方块新的像素外接框 */

    if (on) {   /* 如果需要显示 */
        x1 = X0 + cur_x * CELLX;   /* 左边缘 */
        y1 = Y0 + cur_y * CELLY;   /* 上边缘 */
        x2 = X0 + (cur_x + pmax_x + 1) * CELLX - 1;   /* 右边缘 */
        y2 = Y0 + (cur_y + pmax_y + 1) * CELLY - 1;   /* 下边缘 */
    }   /* 判断结束 */

    /* 没变——最糟的情况也无非是方块停在堆上、等着下一次重力再判失败，但它同时也
       涵盖了暂停，以及"方块已锁定、spawn() 还没把下一块拉进来"的那一帧。 */
    if (on && pcb1 >= 0 && cur_type == pbt && cur_rot == pbro &&   /* 如果方块还在、而且类型形状和上次一样 */
        cur_x == pbx && cur_y == pby)   /* 行列位置也一样 */
        return;   /* 那就不用重画，直接返回 */

    {   /* 开始算这一帧要重画哪儿 */
        int near = (x1 <= pcb2 && pcb1 <= x2) && (y1 <= pby2 && pby1 <= y2);   /* 判断新旧框是不是横竖两个方向都重叠 */

        if (pcb1 >= 0 && on && near) {   /* 如果两框重叠 */
            int ux1 = (pcb1 < x1) ? pcb1 : x1;   /* 并集左边缘 */
            int uy1 = (pby1 < y1) ? pby1 : y1;   /* 并集上边缘 */
            int ux2 = (pcb2 > x2) ? pcb2 : x2;   /* 并集右边缘 */
            int uy2 = (pby2 > y2) ? pby2 : y2;   /* 并集下边缘 */
            mark_dirty_slot(DS_PIECE, ux1, uy1, ux2, uy2);   /* 一个矩形就搞定，同时擦旧画新 */
        } else {   /* 否则两框分得很开 */
            if (pcb1 >= 0) mark_dirty_slot(DS_PIECE,  pcb1, pby1, pcb2, pby2);   /* 先把旧位置标进去，擦掉它 */
            if (on)        mark_dirty_slot(DS_PIECE2, x1,   y1,   x2,   y2);   /* 再把新位置标进第二个槽 */
        }   /* 判断结束 */
    }   /* 标记结束 */
    pcb1 = -1;   /* 旧框记录置为无效 */
    if (!on) { pbt = -1; return; }   /* 方块不显示了就清掉形状记录并返回 */

    pcb1 = x1; pby1 = y1; pcb2 = x2; pby2 = y2;   /* 记下这次的包围框 */
    pbt = cur_type; pbro = cur_rot; pbx = cur_x; pby = cur_y;   /* 记下类型、旋转和行列 */
}   /* 函数结束 */

/* ------------------------------------------------------------------ */
/* 读按键                                                               */
/*                                                                      */
/* 硬件的规则：REG_KEY 的第 n 位就是板子上的第 n+1 个键。绝大多数键是      */
/* 「按下 = 0、松开 = 1」，只有 K1（左）和 K3（右）两位反过来（空闲 0、按  */
/* 下 1），所以换算时要按 KEY_ACTIVE_HIGH_MASK 区别对待（见该宏的注释）。   */
/* 这里只做两件事：把原始电平换算成「按下 = 1」，以及连读两次把毛刺滤掉。   */
/*                                                                      */
/* 以前这里还有一段"开机自动测极性"的校准：前 16 帧逐位统计电平，再按多数  */
/* 表决决定每一位是高有效还是低有效。它看着聪明，实际是个大坑——画面刚亮的 */
/* 那 0.27 秒里，人正好伸手去按开始键；只要某个键在这段窗口里被按住，它就   */
/* 会被判成"空闲是低电平"，之后整场都反着读：松开当成按下、按下当成松开。   */
/* 表现出来就是这个键"失灵"了。现在硬件极性是固定的，别再猜，直接按低有效  */
/* 读。                                                                  */
/* ------------------------------------------------------------------ */
static const uint32_t KEY_MASK = (1u << KEYS_USED) - 1u;   /* 只保留低 8 位的掩码 */

static uint32_t read_keys(void)   /* 读取 8 个按键，返回「哪些键正被按住」的掩码（1 = 按着） */
{   /* 函数体开始 */
    /* 74HC165 每 7.4 毫秒会移位约 5 微秒；如果读取正落在这段窗口里，就可能读到
       一些瞬时跳变的位。连读两次再取"与"，只保留两次都判为按下的位，就把这些
       鬼影抖掉了。 */
    uint32_t a = (apb_read(REG_KEY) ^ ~KEY_ACTIVE_HIGH_MASK) & KEY_MASK;   /* 第一次读，并按各位的极性换算成「1 = 按下」 */
    uint32_t b = (apb_read(REG_KEY) ^ ~KEY_ACTIVE_HIGH_MASK) & KEY_MASK;   /* 紧接着再读一次 */
    return a & b;   /* 两次都判为按下的位，才算真的按下 */
}   /* 函数结束 */

/* ------------------------------------------------------------------ */
int main(void)   /* 程序入口，开机后从这里开始跑 */
{   /* 函数体开始 */
    uint32_t prev_pressed = 0;   /* 上一帧的按键状态，用来判断「这一帧刚按下」 */
    int r;   /* 临时存放函数的返回值 */

    running = 0;              /* 屏幕先空着，等按下 KEY_ROT_CW 才开始游戏 */
    refresh_values();            /* 数值是烤好的，所以先格式化一遍 */
    r = video_boot(tetris_pal, 16);   /* 启动显示后端：装入 16 色调色板并点亮屏幕 */
    sound_init();                /* 启动 SysTick 蜂鸣器（没有音符时是静音的） */

    /* 待机画面：什么都不动。"每一帧"都去轮询按键，这样第一次按 KEY_ROT_CW（上）
       就能立刻开始游戏。以前固定等约 1.5 秒去获取 HDMI，会把那第一次按下给吞掉。 */
    spr_off(0); spr_off(1); spr_off(2); spr_off(3); spr_off(4);   /* 先把五个硬件矩形都关掉 */
    for (;;) {   /* 待机循环：一直转，等玩家按开始键 */
        uint32_t pressed, press_edge;   /* 本帧按住的键，以及本帧刚按下的键 */
        wait_frame();   /* 等一帧，跟着屏幕刷新节拍走 */
        pressed      = read_keys();   /* 读当前按键 */
        press_edge   = pressed & ~prev_pressed;   /* 只有这一帧新按下的才算「边沿」 */
        prev_pressed = pressed;   /* 更新上一帧的记录 */
        if (press_edge & (1u << KEY_ROT_CW)) {   /* 如果刚按下了顺时针旋转键，也就是「上」 */
            init_game();                 /* 清空棋盘、给 NEXT 队列填上方块、并生成第一个方块 */
            running = 1;   /* 进入游戏状态 */
            sound_start_bgm();           /* 开始游戏时放背景音乐 */
            break;   /* 跳出待机循环，开始正式游戏 */
        }   /* 判断结束 */
        spr_off(0); spr_off(1); spr_off(2); spr_off(3); spr_off(4);   /* 待机时让硬件矩形保持全关 */
    }   /* 待机循环结束 */

    game_key_tick();   /* 进入游戏前先把按键状态对齐一次 */
    key_edge = 0u;     /* 待机期间攒的边沿不要带进游戏，免得一开局就误触 */

    while (1) {   /* 游戏主循环：每帧跑一次，一直不停 */
        uint32_t pressed, press_edge;   /* 本帧按住的键，以及刚按下的键 */

        /* 60 Hz 节拍：面板每个显示帧都会交出一个新的空闲缓冲区，所以按帧计数器
           来定节奏，也就给了三重缓冲那次握手（BUF_FREE / BUF_POST 要跨时钟域）
           整整一帧的时间稳定下来，之后才去读 buf_begin()。 */
        /* 等这一帧的空当里持续采键盘。重画那段（几十毫秒）也不是瞎子：HAL 每算
           完一块显存就会回调 game_key_tick()，把"刚按下"攒进 key_edge。所以这里
           只要在帧首把闩锁取走，帧里任何时刻的点按都不会丢。 */
        {
            uint32_t f0    = apb_read(REG_FRAME) & 0xFFu;   /* 先记住现在的帧号 */
            uint32_t guard = 0x200000u;   /* 防死等的上限（正常永远用不到） */

            game_key_tick();   /* 先自己采一次，当作这段等待的起点 */
            while ((apb_read(REG_FRAME) & 0xFFu) == f0) {   /* 帧号还是老样子就继续等 */
                game_key_tick();   /* 趁等帧顺手再采一次 */
                if (--guard == 0u) break;   /* 万一帧号一直不动，也别卡死在这儿 */
            }   /* 等待循环结束 */
            game_key_tick();   /* 新的一帧到了，再采最后一次，让 pressed 足够新 */

            pressed    = key_level;   /* 这一帧按着哪些键 */
            press_edge = key_edge;    /* 上一帧重画期间 + 这段等待里攒下的全部"刚按下" */
            key_edge   = 0u;          /* 取走了就清空，下一帧从零开始攒 */
        }
        r = buf_begin();   /* 开始操作这一帧拿到的缓冲区，r 是它的编号 */
        next_flush();   /* 把上一帧压下来的 NEXT 条重画，在这一帧补上 */

        {   /* 这一帧的游戏逻辑开始 */
            if (++blink_cnt >= 32) blink_cnt = 0;   /* 闪烁计数器每帧加一，数到 32 就归零，这就是一个闪烁周期 */

            /* 游戏结束画面分"两个阶段"，两阶段都是烤好的（见 game_pixel）、也都会
               闪：先显示 GAME OVER 字样 GO_HOLD 帧，然后同一带换成 PRESS TO
               CONTINUE，直到任意键开新局。只有"内容变化"才会重画这一带，所以
               闪烁的两次翻转、以及那一次阶段切换，是唯一会碰到它矩形的几帧。 */
            if (game_over) {   /* 如果已经顶出天花板了 */
                int on, key;   /* 本帧横幅亮不亮，以及状态码 */
                go_frames++;   /* 结束画面已过的帧数加一 */
                if (go_phase == 0 && go_frames >= GO_HOLD) {   /* 第一阶段已经闪够了指定帧数 */
                    go_phase = 1;   /* 切换到第二阶段，也就是显示提示 */
                    blink_cnt = 0;          /* 把闪烁计数清零，让提示语一出现就是亮的 */
                }   /* 判断结束 */
                on       = (blink_cnt < 16);   /* 闪烁前半周期亮、后半周期灭 */
                go_shown = on;   /* 更新横幅此刻亮不亮 */
                key      = on | (go_phase << 1);   /* 把亮不亮和阶段合成一个状态码 */
                if (key != ban_state) {   /* 如果和上次记录的状态不一样 */
                    ban_state = key;   /* 记下新状态 */
                    mark_dirty_slot(DS_BANNER, BAN_X, BAN_Y,   /* 标记横幅区域要重画 */
                                    BAN_X + BAN_W - 1, BAN_Y + BAN_H - 1);   /* 一直到横幅右下角 */
                }   /* 判断结束 */
            }   /* 游戏结束这段处理结束 */

            /* K8 = 暂停：按一下冻结、再按一下恢复（顶出天花板时不响应） */
            if (!game_over && (press_edge & (1u << KEY_PAUSE))) paused = !paused;   /* 按暂停键就切换暂停和继续，游戏没结束才有效 */

            if (game_over) {   /* 如果游戏结束了 */
                /* 顶出天花板之后：GAME OVER 字样亮着时只跑闪烁；等 PRESS TO
                   CONTINUE 提示亮满 GO_GUARD 帧之后，任意键都能开新局。这道
                   保险是为了防止"刚刚把游戏顶出局的那次按键"——或者慌乱中一通
                   乱按——在玩家还没来得及看清画面时就把它跳过去。 */
                if (go_phase == 1 && go_frames >= GO_HOLD + GO_GUARD &&   /* 第二阶段提示已经亮够了安全帧数 */
                    press_edge != 0u) {   /* 并且玩家按了任意键 */
                    spr_off(0); spr_off(1); spr_off(2); spr_off(3); spr_off(4);   /* 先关掉所有硬件矩形 */
                    init_game();   /* 重开一局 */
                    sound_start_bgm();   /* 新开一局 → 重新开始放音乐 */
                    /* 把旧方块、面板、分数以及那句提示，从"全部三个"缓冲区里都
                       擦掉；上面的纯色背景永远不变，所以重画从场地外框的顶部
                       开始就够了 */
                    mark_dirty(0, Y0 - BORDER, HOR_PIXELS - 1, VER_PIXELS - 1);   /* 让三个缓冲区都重画场地那一整片，把旧画面擦干净 */
                }   /* 判断结束 */
            } else if (paused) {   /* 否则如果正在暂停 */
                /* 冻结状态：不处理输入、不走重力、也不重画 */
            } else {   /* 否则就是正常的游戏帧 */
                /* 新的方块在 lock_piece() 里已经上场了，所以这一帧的输入和重力
                   直接作用在它身上——方块刚出现的那一帧按硬降／HOLD 就生效，
                   不用再等它先往下走两行。如果生成时就把游戏顶出局了，那就
                   没什么可操纵的了，这一帧剩下的部分直接跳过。 */
                if (!game_over) {   /* 如果这一帧还有方块可操纵，就继续处理输入 */
                    /* 左右：按下时立刻先移一格，之后过了 DAS_INITIAL 帧才开始
                       自动连发。dir_keys 把"刚按下"也算进来：帧率不高的时候，
                       一次快速点按可能整个发生在两帧之间，到帧首时键已经松开，
                       只看 pressed 会把它整个丢掉——表现出来就是"点了没反应、
                       要按住才动"。加上 press_edge 后，这种点按也一定走一格，
                       而且按住时只会触发一次，不会多走。 */
                    uint32_t dir_keys = pressed | press_edge;   /* 按着或这一帧刚按过都算 */
                    int dir = (dir_keys & (1u << KEY_LEFT)) ? -1 :   /* 算左右移动方向：按左是 -1 */
                              (dir_keys & (1u << KEY_RIGHT)) ? 1 : 0;   /* 按右是 1，都不按就是 0 */
                    if (dir == 0) { das_dir = 0; das_cnt = 0; }   /* 没按方向键就复位连发状态 */
                    else if (dir != das_dir) { das_dir = dir; das_cnt = DAS_INITIAL; try_move(dir, 0); }   /* 刚换方向：先立刻移一格，并开始连发倒计时 */
                    else if (das_cnt > 0) { das_cnt--; }   /* 还在首次延迟里，只是把倒计时减一 */
                    else { try_move(dir, 0); das_cnt = DAS_REPEAT; }   /* 延迟到了：再移一格，并把倒计时重置成连发间隔 */

                    /* K2 = 顺时针旋转，K7 = 逆时针旋转——每按一次转一下 */
                    if (press_edge & (1u << KEY_ROT_CW))  do_rotate(+1);   /* 刚按下顺时针旋转键：转一下 */
                    if (press_edge & (1u << KEY_ROT_CCW)) do_rotate(-1);   /* 刚按下逆时针旋转键：反向转一下 */

                    /* K6 = 把方块存起来／交换（每个方块只能用一次） */
                    if (press_edge & (1u << KEY_HOLD)) do_hold();   /* 刚按下 HOLD 键：换存方块 */

                    /* K5 = 硬降：一下砸到底并立刻落定。它结束了这个方块的"回合"，
                       所以同一帧里就不再走重力了。 */
                    if (press_edge & (1u << KEY_HARD_DROP)) {   /* 刚按下硬降键 */
                        do_hard_drop();   /* 执行硬降 */
                    } else if (!game_over) {   /* 否则没按硬降，就走正常重力 */
                        /* 走重力，或者按住 K4 时走更快的手动下落。try_move 只在
                           目标格子空着、而且还在井内时才真的移动方块，所以它既不
                           能穿进方块里，也不能穿过地板。 */
                        /* 按住 K4 时每帧下落 1 行。等级 0 的重力是两帧一格，
                           所以软降是重力速度的 2 倍；等级再高重力最快也只到
                           一帧一格，软降最多和重力持平（不会再变慢）。
                           旧版本 SOFT_REPEAT=2 与 GRAV_FRAMES=2 相等，按住 K4
                           反而完全不加速，这才是"方块按不下去"的根因。
                           一帧两行切换成一帧一行，是因为两行/帧（4 倍重力）
                           在方块刚出生的那一段掉得太猛，锁定得太快，NEXT／
                           HOLD 面板来不及重画，看起来就像有残影。
                           press_edge 也参与判断：这一帧刚按下的 K4 立刻生效，
                           不用再等下一帧才开始下落。 */
                        if ((pressed | press_edge) & (1u << KEY_SOFT_DROP)) {   /* 按着或刚按下软降键 */
                            grav_cnt = 0;          /* 手动下落时把重力计时重新对一下 */
                            if (!try_move(0, 1)) lock_piece();   /* 往下移一格，移不动就落定 */
                        } else {   /* 否则没按软降键，走正常重力 */
                            if (++grav_cnt >= grav_frames()) { grav_cnt = 0; if (!try_move(0, 1)) lock_piece(); }   /* 重力计时到了就往下掉一格，掉不动就落定 */
                        }   /* 判断结束 */
                    }   /* 重力这段判断结束 */
                }   /* 没顶出判断结束 */
            }   /* 正常游戏帧处理结束 */
        }   /* 游戏逻辑结束 */

        ghost_sync();              /* 让烤好的落点预览跟上方块——方块单纯下落时它不花代价 */
        piece_sync();              /* ……以及方块自己，它烤制的原因和残影一样 */

        publish_sprites();   /* 更新硬件矩形，比如暂停图标 */

        if (dirty[r].pend) {   /* 如果这个缓冲区有待重画的矩形 */
            int i, k, n;   /* 遍历序、槽号、这个矩形要花几块 */
            int used = 0;   /* 这一帧已经写了多少块显存 */
            int opt_used = 0;   /* 其中属于"可缓"的次要矩形有多少块 */
            int done = 0;   /* 第 k 位为 1 = 这个槽这一帧已经处理完了 */
            int spilled;   /* 这一帧有没有被顶出一个整帧 */
            uint32_t f_before = apb_read(REG_FRAME) & 0xFFu;   /* 画之前先记一下帧号，用来量这一帧有没有超时 */

            /* 先把重复的矩形并掉：硬降那一帧"方块新位置 + 场地框 + 残影框"
               盖的是同一片地方，分开画等于把同样的块写三遍（见 merge_dirty）。
               这一下把方块刚出生那几行的硬降工作量直接砍掉三分之一。 */
            merge_dirty(r);

            /* 整个脏区域集合还是做"一次事务"：每个矩形都进同一批，最后整批
               一次性推出去，所以 N 个矩形依然只花一个写窗口，而不是 N 个。 */
            paint_begin();   /* 开始一次批量绘制，也就是开一个写窗口 */

            /* 按"玩家最在意谁"的顺序画，而且一帧只写有限块：显存写只能挤在
               垂直消隐那 1.4ms 里，块数一多就得多等一个整帧（16.7ms），
               画面反而更慢。所以塞不下的次要矩形原地留着，下一帧再画——
               残影、分数晚一帧没人看得出来，方块的位置不能晚。 */
            for (i = 0; i < DIRTY_SLOTS; i++) {   /* 按优先级逐槽处理 */
                int must;   /* 这个矩形是不是"这一帧非画不可"的 */
                k = paint_order[i];   /* 这一轮该看哪个槽 */
                if (!(dirty[r].pend & (1 << k))) continue;   /* 这个槽没有矩形就跳过 */

                n = rect_blocks(dirty[r].x1[k], dirty[r].y1[k],   /* 先算这个矩形要花几块 */
                                dirty[r].x2[k], dirty[r].y2[k]);

                /* 分数、等级、行数这三行文字也必须是"这一帧非画完不可"的。
                   以前它们留作可选槽，本意是给重画留点余量；但连续快速按键
                   （尤其是连着硬降）时，分数每次都在变，而分数那一帧往往正好
                   撞上场地大面积重画，预算被顶满，分数就被一帧帧顺延。三个
                   缓冲区各自记脏，顺延期间它们显示的还是各自的旧分数，轮换
                   上屏时就会看到新旧数字叠在一起，像是分数有残影。这三块都
                   只有 72x14 像素，真要画的时候成本很低，没必要顺延。
                   横幅会周期性闪烁，面积也大，仍然允许晚一帧。 */
                must = (k != DS_BANNER);

                /* 次要的：已经画了东西、再加它会超出本帧预算，就留到下一帧
                   （用 continue 而不是 break，免得一个塞不下的大框把后面那些
                   小块也一起拖住）。 */
                if (!must && used > 0 && used + n > paint_budget) continue;

                paint_rect(dirty[r].x1[k], dirty[r].y1[k],   /* 真的画出来 */
                           dirty[r].x2[k], dirty[r].y2[k]);
                used += n;   /* 记账 */
                if (!must) opt_used += n;   /* 次要的单独记一笔，校准预算时用得上 */
                done |= 1 << k;   /* 这个槽这一帧处理完了 */
            }   /* 逐槽循环结束 */
            paint_end();   /* 结束批量，把整批一次性推给硬件 */
            dirty[r].pend &= ~done;   /* 只清掉这一帧真的处理过的槽，没画的留到下一帧 */

            /* 量一下这次画了多久：帧号翻了 = 这一帧没赶上，多等了一个整帧。
               这时候下次就按"这一帧非画不可的那部分 + 一点点余量"重定预算，
               把次要内容管紧；帧号没翻 = 准点上屏，就慢慢把预算放回去，试探
               硬件到底一帧吃得下多少块。 */
            spilled = ((apb_read(REG_FRAME) & 0xFFu) != f_before);
            if (!spilled) {   /* 这一帧准点上屏 */
                if (paint_budget < 96) paint_budget += 4;   /* 还宽裕：一次加一点 */
            } else {   /* 没赶上 */
                int nb = (used - opt_used) + 16;   /* 按"必须画的那部分"再加上一点余量 */
                if (nb < 24) nb = 24;   /* 别再低下去：太低会让 HOLD 窗、分数排着队画不上 */
                if (nb < paint_budget) paint_budget = nb;   /* 只收紧，不放松 */
            }   /* 校准结束 */
        }   /* 判断结束 */

        buf_post(r);   /* 把画好的缓冲区交给显示，让它上屏 */
    }   /* 主循环结束 */
}   /* 函数结束 */
