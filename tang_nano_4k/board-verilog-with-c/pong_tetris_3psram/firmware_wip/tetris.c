/*
 * tetris.c - 俄罗斯方块。整个游戏全部用 C 语言写，跑在一个「跟游戏无关」的
 * 显示后端上（也就是 fabric，和 pong.c 用的是同一套 HAL；编译时用这个文件
 * 代替 pong.c）。
 *
 * 分工，和 Pong 完全一样：
 *   fabric（FPGA 里的 Verilog）：把一块 320x240、每像素 8 位、存的是调色板
 *            编号（0~15，叫「索引色」）的显存，横竖各放大 2 倍，输出成
 *            640x480@60 的 HDMI 画面；一张 16 项的调色板；5 个可以随便摆
 *            位置的纯色矩形；一个能读 8 个按键的移位寄存器；还有三缓冲显示
 *            （存三整帧，换着看）。就这些，没有别的。
 *   这个 C 文件：场地和已经落定的方块、正在下落的活动方块、HOLD / NEXT 两个
 *            小窗、以及落点预览（残影）——全都直接画进显存，因为现在每一个
 *            格子都是「带高光的格子」（左上角有一个亮角），而显示后端的矩形
 *            只能填一种纯色。另外还负责 7 种方块形状、旋转、碰撞、下落、消行、
 *            计分，以及画面两侧的面板：左边缘竖着排 HOLD + SCORE、LEVEL、
 *            LINES，右上角横着排三个 NEXT。
 *
 * 「带高光的格子」——这里说的「不是纯色」是什么意思
 *   调色板那 16 项颜色是写死在 Verilog 里的（palette_ram.v，地址 =
 *   pix_idx[3:0]），而 GW1NSR-4C 芯片的寄存器已经用满，腾不出地方把颜色
 *   加多，所以高光不能靠「多几种颜色」来做。改成用「几何形状」来做：每个
 *   格子都先用方块自己的颜色填充，再在左上角沿对角线画一个亮三角（调色板
 *   编号 1，白色），看起来就像斜切的边加一点高光；而格子的最后一行和最后一
 *   列保持背景色，也就是把一个个小方块隔开的暗色接缝。一个格子，一个函数：
 *   cell_body()。
 *
 *   因为「正在下落的方块」和「已经落定的方块」是用同一个格子函数画的，
 *   所以落定的那一刻像素完全一样、不需要额外重画——这也正是能承受把它画进
 *   显存的原因（落定时只需要把方块离开的那两三个格子，通过 piece_sync()
 *   补一下）。
 *
 * 下面所有坐标都在 320x240 的低分辨率坐标系里：显示后端会帮你乘 2，所以
 * 这里永远不用提 640x480。
 *
 * 按键：这 8 个按键的含义和参考固件里完全一致，所以在那边干什么、在这里也
 *   干什么。游戏按键 K1..K4 = 寄存器第 0..3 位，从左到右就是 K1、K2、K3、
 *   K4：K1 左移，K3 右移，K2（上）顺时针旋转，K4（下）加速下落。
 *   K5 把方块一砸到底（硬降），K6 和 HOLD 槽互换，K7 逆时针旋转，K8 暂停。
 *   顶到天花板（top-out）之后，先闪一会儿 GAME OVER 字样，再换成
 *   PRESS TO CONTINUE 在同一位置闪；这时按任意键就开新一局。
 *   read_keys() 返回一个掩码：某个键按着就是 1（寄存器里按下是 0，这里统一
 *   翻成 1，游戏逻辑只认这个掩码）。
 * 想改键位，只改下面那几个 #define 就行——其它地方都不依赖具体键位。
 */
/* ------------------------------------------------------------------ */
/* 按键边沿闩锁                                                        */
/*                                                                     */
/* 主循环不是每时每刻都在看键盘：一帧里有一大段在重画（算像素、推显存）， */
/* 硬降/HOLD 触发的那些帧尤其长。以前只在"等下一帧"的空当里读键盘，于是  */
/* 一次很快的点按如果整段都落在重画那几十毫秒里，就会被彻底漏掉——表现   */
/* 就是"按了没反应，方块继续往下走"。                                  */
/*                                                                     */
/* 现在 HAL 每算完一块（128 像素）就回调下面这个函数采一次键盘，把新出现  */
/* 的"刚按下"攒进 key_edge，主循环在下一帧帧首一次性取走。这样无论一次   */
/* 点按落在帧里的哪个位置，都不会丢。                                   */
/* ------------------------------------------------------------------ */
static void game_key_tick(void);   /* 先打个招呼：反正是个「采一次键盘」的函数，函数体在下面 */

/* 告诉 HAL：每算完一块显存就回调一次 game_key_tick()。
   宏必须在包含 game_hal.h 之前定义好，因为 stage_block() 是在头文件里写的。 */
#define GAME_KEY_TICK() game_key_tick()

#include "game_hal.h"   /* 引入硬件接口头文件：屏幕、按键、蜂鸣器要用的函数都在这里声明 */

static uint32_t key_level;      /* 最近一次采样看到的「按着哪些键」（1 = 按着） */
static uint32_t key_edge;       /* 攒下来、还没被主循环取走的「刚按下」 */
static uint32_t key_raw_prev;   /* 上一次采到的原始按键，跨采样点滤毛刺用 */

/* 本机键盘的 k1(左) 和 k3(右) 这两位是「空闲 = 0、按下 = 1」，
   其余 6 位是「空闲 = 1、按下 = 0」。所以读寄存器时，除了这两位以外
   都要取反。这个掩码就是「不要取反」的位：
     bit0 = K1 = 左移
     bit2 = K3 = 右移
   实测依据：不按键时方块自动左滑、按左往右走、按右往左走；只有这两位
   的空闲电平与其它键相反时，这三种现象才能同时成立（详见
   「键盘问题_原因和解决方案.md」第 8.4 节）。 */
#define KEY_ACTIVE_HIGH_MASK ((1u << 0) | (1u << 2))

static void game_key_tick(void)   /* 采一次键盘，把新出现的按下边沿攒起来 */
{   /* 函数体开始 */
    uint32_t now, stable;   /* 这一次采到的原始值，以及和上一次采样的交集 */

    /* 只在一次调用里连读两遍是不够的：两次读相隔只有约 1 微秒，而 74HC165
       每 7.4 毫秒会移位约 5 微秒，两遍很可能一起落进同一个移位窗口，读到
       同一个错误值，取"与"也挡不住。这个函数被 HAL 每画完一块显存就回调
       一次，相邻两次调用相隔几十微秒，已经大于整个移位窗口，所以改成
       "这一次采到的值 与 上一次采到的值"取交集，就能把移位窗口里的瞬时
       毛刺（典型表现是低几位被读成 0，方块自己往左漂）滤干净。 */
    /* 先用 ^ ~KEY_ACTIVE_HIGH_MASK 把 K1/K3 之外的 6 位取反（那两位保持原样），
       再把 1 当成"按下"。 */
    now    = (apb_read(REG_KEY) ^ ~KEY_ACTIVE_HIGH_MASK) & 0xFFu;   /* 读一次并换算成「1 = 按下」 */
    stable = now & key_raw_prev;             /* 和上一次采样都为"按下"才算数 */
    key_raw_prev = now;                      /* 记下这一次的原始值 */

    key_edge |= stable & ~key_level;   /* 这一拍新出现的按下，攒进闩锁 */
    key_level = stable;   /* 记住这一拍的状态，下一次比较用 */
}   /* 函数结束 */

