static uint32_t snd_left;        /* 当前这个音还剩多少个滴答              */
static uint32_t snd_half;        /* 当前这个音的半周期有多少滴答           */
static uint32_t snd_half_left;   /* 距离下一次翻转蜂鸣器还有多少滴答       */
static uint8_t  snd_level;   /* 蜂鸣器引脚此刻是高还是低 */
static uint8_t  snd_mode;   /* 当前声音状态：空闲、放音乐、放音效、还是放结束曲 */
static uint16_t snd_gap;         /* 接回时那段静音要留多少个滴答           */

/* 记下一次性音效抢走蜂鸣器时，音乐正播到哪儿：是哪个音、还剩多少。
   这里故意不把正在响的半周期原样接回去——接回处会留一小段静音、再干净
   地重新起头（见 snd_after_fx）。 */
static uint16_t r_pos;   /* 被音效打断时，音乐停在第几个音符 */
static uint32_t r_left, r_half, r_half_left;   /* 记下当时那个音符还剩多少滴答、半周期是多少、半周期还剩多少 */
static uint8_t  r_valid;   /* 等于 1 表示确实有一首音乐被打断、稍后要接着播 */

/* 排在"当前正在播的那个音效"后面、等它播完就接着响的一次性音效——只有
   一个槽位，因为这游戏永远只串一件事（消行滑音之后紧接升级叮声）。它不算
   音乐恢复的一部分，所以新开一段曲子或放结束主题时，会干脆把它忘掉。 */
static const Note *snd_next_seq;   /* 排队等着播的下一个音效，比如消行后紧接着的升级叮声 */
static uint16_t snd_next_len;   /* 那个排队音效有多少个音符 */
static uint8_t  snd_next_valid;   /* 等于 1 表示真的有音效在排队 */

/* 蜂鸣器寄存器就是一个普通的电平值，写一次之后硬件会一直保持住
   （apb_fb_reg.v 里就是 beep_trig <= pwdata[0]，不会自动清零），所以写一个
   它本来就等于的值除了白白占用一次 APB 写之外毫无作用——而以前休止和空闲
   时每秒要写 0 三万次。这里把引脚的当前值记在软件里，只有真要变化时才去碰
   寄存器。 */
static uint8_t beep_lvl;   /* 记着蜂鸣器引脚当前的值，避免重复写寄存器做无用功 */

static void beep_out(int level)   /* 设置蜂鸣器输出电平，只在真的要变化时才去写寄存器 */
{   /* 函数体开始 */
    uint8_t v = (uint8_t)(level ? 1u : 0u);   /* 把传进来的值规整成 0 或 1 */
    if (v != beep_lvl) {   /* 只有和上次不一样才需要动硬件 */
        beep_lvl = v;   /* 记下新电平 */
        beep_set((int)v);   /* 真正写硬件寄存器、让蜂鸣器改变电平 */
    }   /* 判断结束 */
}   /* 函数结束 */

/* 断音（articulation）。一位的蜂鸣器没有音量包络，所以音符一个接一个连下去
   听起来就是一串不停的嗡声——以前音乐就是那个样子。办法是在音乐和结束音的
   每个音符最后约 13 毫秒里把电平压在 0，这样音符之间就分开了，而又不改变
   曲子本身。这个切音会推迟到当前半周期走完时才做，于是波形是停在过零点上、
   而不是半周期中间（停在中间就是一声咔哒，旧代码按音符切音正好切在中间）。
   消行那串滑音例外：它的音符又短又快，它整个的意义就是那串连续滑音，而且
   它本来就听得清楚。 */
#define GATE_TICKS  400         /* 按 SND_RATE 算大约是 13 毫秒 */

static void snd_begin(const Note *seq, uint16_t len)   /* 从头开始播放一段乐谱 */
{   /* 函数体开始 */
    snd_seq = seq; snd_len = len;   /* 记下要播的乐谱和它的长度 */
    snd_pos = 0;   /* 从第 0 个音符播起 */
    snd_level = 0;   /* 输出电平先归零 */
    snd_half = seq[0].half;   /* 取出第一个音符的半周期，这决定音高 */
    snd_left = seq[0].ticks;   /* 取出第一个音符要持续多少个滴答 */
    snd_half_left = snd_half;   /* 下一次翻转电平的倒计时从满值开始 */
    beep_out(0);   /* 蜂鸣器先静音 */
}   /* 函数结束 */

/* 背景音乐，从头开始。 */
static void sound_start_bgm(void)   /* 开始播放背景音乐 */
{   /* 函数体开始 */
    r_valid = 0;                     /* 全新开一段曲子不算「恢复」 */
    snd_next_valid = 0;              /* 顺便把排队的音效也丢掉 */
    snd_mode = SM_BGM;   /* 把声音状态设成「正在放音乐」 */
    snd_begin(bgm, BGM_N);   /* 从头开始播背景音乐 */
}   /* 函数结束 */

/* 顶到上限那首曲子，从头开始；中断服务程序会让它原地循环。 */
static void sound_over(void)   /* 播放游戏结束主题曲 */
{   /* 函数体开始 */
    r_valid = 0;   /* 没有被打断的音乐需要恢复了 */
    snd_next_valid = 0;   /* 清掉排队的音效 */
    snd_mode = SM_OVER;   /* 状态设成「结束曲循环中」 */
    snd_begin(fx_over, OVR_N);   /* 从头播游戏结束主题 */
}   /* 函数结束 */

/* 一次性音效：它整段期间独占蜂鸣器，这就是为什么放消行滑音时，底下音乐是
   静音的、滑音能单独听清。如果已经有一个音效在响时又来第二个，就只是把它
   顶替掉，并保留最开始那个恢复点。 */
static void sound_fx(const Note *seq, uint16_t len)   /* 播放一次性音效，它会把背景音乐暂时抢走 */
{   /* 函数体开始 */
    if (snd_mode == SM_BGM) {   /* 如果此刻正在放背景音乐，先把它记下来 */
        r_pos = snd_pos; r_left = snd_left; r_half = snd_half;   /* 记住音乐播到哪、还剩多少、半周期是多少 */
        r_half_left = snd_half_left;   /* 记住半周期还剩多少 */
        r_valid = 1;   /* 标记「有音乐等着恢复」 */
    }   /* 判断结束 */
    snd_mode = SM_FX;   /* 状态设成「正在放音效」 */
    snd_begin(seq, len);   /* 开始播这个音效 */
}   /* 函数结束 */

/* 把一个一次性音效排到"当前蜂鸣器上那个音效结束的那一刻"开始，这样两个
   音效首尾相接，而不是第二个把第一个掐断。如果当前什么都没响，就立刻播它。
   升级那声叮就是这么紧跟在消行滑音后面、既不留缝也不重叠的。 */
static void sound_fx_after(const Note *seq, uint16_t len)   /* 把一个音效排在当前音效播完之后紧接着播 */
{   /* 函数体开始 */
    if (snd_mode == SM_FX) {   /* 如果现在已经有一个音效在响 */
        snd_next_seq   = seq;   /* 把这个新音效记进排队槽 */
        snd_next_len   = len;   /* 记下它的长度 */
        snd_next_valid = 1;   /* 标记排队槽有效 */
        return;   /* 先不播，等当前音效播完再说 */
    }   /* 判断结束 */
    sound_fx(seq, len);   /* 没有音效在响，那就现在直接播 */
}   /* 函数结束 */

/* 一次性音效播完时由中断服务程序调用：把蜂鸣器交还回去。 */
static void snd_after_fx(void)   /* 一次音效播完时调用：把蜂鸣器交还给音乐 */
{   /* 函数体开始 */
    if (snd_next_valid) {   /* 如果有音效在排队，先播它 */
        /* 接下来由排队的那个音效接管蜂鸣器；这里不用去动恢复逻辑——音乐
           还停在 r_valid 里，等这串音效最后一个播完时自然会接回 */
        snd_next_valid = 0;   /* 清掉排队标记 */
        snd_begin(snd_next_seq, snd_next_len);   /* 开始播排队的那个音效 */
        /* 和下面音乐接回时一样的那段接缝静音，理由也一样：第一个音效的最
           后一个音是被切在半个周期中间的，所以先静一小段、再从电平 0 起、
           落在整周界上。它同时也把两个音效隔开，这正是排队而不把它们串进
           同一张表里的意义。 */
        snd_gap = GATE_TICKS;   /* 留一小段静音，让两个音效分开、也避免咔哒声 */
        return;   /* 本轮结束 */
    }   /* 判断结束 */
    if (r_valid) {   /* 没有排队音效，但之前有音乐被打断过，就恢复它 */
        r_valid  = 0;   /* 清掉恢复标记 */
        snd_mode = SM_BGM;   /* 状态回到「放音乐」 */
        snd_seq  = bgm;   /* 乐谱换回背景音乐 */
        snd_len  = BGM_N;   /* 长度也换回背景音乐的长度 */
        snd_pos  = r_pos;   /* 从刚才被打断的那个音符接着播 */
        snd_left = r_left;   /* 恢复那个音符剩余的滴答数 */
        snd_half = r_half;   /* 恢复它的半周期 */
        snd_half_left = r_half_left;   /* 恢复半周期剩余的量 */
        /* 接回处的接缝。音乐回来之前先静一个闸门的时间，并让载波从电平 0、
           整周界开始：没有这一步的话，音效最后一个音会以它被切断时的任意
           相位直接撞进恢复的那个音，而且恢复出来的电平可能和引脚差了半个
           周期，于是第一次翻转成了一次没改变任何东西的空写、低电平那半拍
           被拉长。那声咔哒就是音乐一回来听到的杂音。约 13 毫秒不会被听成
           停顿，但接缝就不响了。 */
        snd_level = 0;   /* 电平从 0 重新开始，避免第一下翻转是空写 */
        snd_half_left = snd_half;   /* 从完整的一个半周期开始数 */
        snd_gap = GATE_TICKS;   /* 同样留一小段静音做接口 */
        return;   /* 本轮结束 */
    }   /* 判断结束 */
    snd_mode = SM_IDLE;   /* 什么都没有，就彻底静下来 */
    snd_seq  = 0;   /* 清空当前乐谱指针 */
    beep_out(0);   /* 蜂鸣器静音 */
}   /* 函数结束 */

static void sound_init(void)   /* 初始化声音系统 */
{   /* 函数体开始 */
    r_valid  = 0;   /* 没有要恢复的音乐 */
    snd_mode = SM_IDLE;   /* 一开始是静音状态 */
    snd_seq  = 0;   /* 没有乐谱 */
    snd_gap  = 0;   /* 不需要静音间隔 */
    beep_lvl = 0;                    /* 复位时也归 0，和引脚上电默认的 0 一致 */
    SysTick->CTRL = 0u;   /* 先关掉 SysTick 定时器 */
    SysTick->LOAD = (uint32_t)(FCPU / SND_RATE) - 1u;   /* 设置定时器的重载值，让它每秒中断 3 万次 */
    SysTick->VAL  = 0u;   /* 计数器清零 */
    SysTick->CTRL = SysTick_CTRL_CLKSOURCE_Msk |   /* 打开定时器：选择核心时钟源， */
                    SysTick_CTRL_TICKINT_Msk   |   /* 允许它产生中断， */
                    SysTick_CTRL_ENABLE_Msk;   /* 并且启动它 */
}   /* 函数结束 */

void SysTick_Handler(void)   /* 定时器中断处理函数，每 1/30000 秒自动被调用一次 */
{   /* 函数体开始 */
    uint32_t half;   /* 临时存放当前音符的半周期 */

    if (!snd_seq) { beep_out(0); return; }   /* 没有乐谱在播就直接静音、返回 */

    /* 音效播完接回音乐时的那个"接缝"（详见 snd_after_fx）：先保持静音，
       而且在这段静音间隔倒计时期间，要把刚接回来的那个音符"冻住"——
       它的剩余时长不能被这段静音悄悄吃掉。 */
    if (snd_gap) { --snd_gap; beep_out(0); return; }   /* 还在静音间隔里就继续静音并倒计时 */

    if (--snd_left == 0u) {   /* 当前音符的时长倒数到 0，就该换下一个音符了 */
        snd_pos++;   /* 指向下一个音符 */
        if (snd_pos >= snd_len) {   /* 如果这段乐谱播到头了 */
            if (snd_mode == SM_FX) {   /* 一次性音效播完 → 该把音乐接回来了 */
                snd_after_fx();   /* 音效播完，把蜂鸣器还给音乐 */
                return;   /* 本轮结束 */
            }   /* 判断结束 */
            snd_pos = 0;               /* 音乐和结束曲都原地循环 */
        }   /* 判断结束 */
        snd_half      = snd_seq[snd_pos].half;   /* 取新音符的半周期 */
        snd_left      = snd_seq[snd_pos].ticks;   /* 取新音符要持续多久 */
        snd_half_left = snd_half;   /* 半周期倒计时从满值开始 */
        if (snd_mode != SM_FX) snd_level = 0;  /* 音效保持它自己的切换节奏，不动电平 */
        beep_out(0);   /* 换音符时先把蜂鸣器压到 0 */
        return;   /* 本轮结束 */
    }   /* 判断结束 */

    half = snd_half;   /* 取出当前半周期 */
    if (half == 0u) { beep_out(0); return; }   /* 休止符 */

    /* 断音／防咔哒闸门——见 GATE_TICKS。只有音乐和结束曲的音符拖得够长、
       才需要这道处理；消行滑音跑得快，用不着。电平是在当前半周期走完时
       才压到 0，而不是闸门一打开的瞬间就压，这样波形能停在过零点上。 */
    if (snd_mode != SM_FX && snd_left <= GATE_TICKS) {   /* 如果不是音效、而且这个音符快到尾巴了，就进入消音门 */
        if (--snd_half_left == 0u) { snd_half_left = half; snd_level = 0; }   /* 半周期走完就把电平压到 0，在过零点切换避免咔哒声 */
        beep_out((int)snd_level);   /* 把当前电平写给蜂鸣器 */
        return;   /* 本轮结束 */
    }   /* 判断结束 */

    if (--snd_half_left == 0u) {   /* 半周期数到头，该翻转一次电平了 */
        snd_level ^= 1u;   /* 电平取反：高变低、低变高，这样就成了方波 */
        /* 只对音乐这么做：用占空比 25% 的脉冲代替标准方波。50% 的标准方波
           有很大一部分能量落在三次谐波上，这就是曲子从蜂鸣器里听起来发刺
           的原因；让引脚只在一半的半周期里保持高电平，就能把这个谐波压低
           约 3 dB。周期不变，所以音高和节奏都原封不动——这正是 Game Boy
           那种脉冲音色。音效则保留标准方波：消行滑音现在的听感已经定下来
           了，结束曲又短又低。 */
        if (snd_mode == SM_BGM) {   /* 如果是背景音乐，就用 25% 占空比让音色柔和一些 */
            uint32_t hi = (half + 1u) >> 1;   /* 算出半个半周期的长度，也就是高电平占的时间 */
            snd_half_left = snd_level ? hi : (half + hi);   /* 高电平少持续一点、低电平多持续一点 */
        } else {   /* 否则是音效 */
            snd_half_left = half;   /* 音效用标准方波，高低各占半个周期 */
        }   /* 判断结束 */
        beep_out((int)snd_level);   /* 把新电平写给蜂鸣器 */
    }   /* 判断结束 */
}   /* 函数结束 */

/* 增量渲染：只画"自上次渲染以来发生变化"的部分，而且是按每个缓冲区最多
   九个互相独立的矩形来记，而不是合并成一个大矩形。

   DS_FIELD ：场地本身——方块落定、消行。
   DS_PANEL ：NEXT 条（每次出生都要重画）。
   DS_HOLD  ：HOLD 小窗（按下 K6 才重画）。
   DS_GHOST ：落点预览（残影）——旧框和新框的并集。
   DS_GHOST2：落点预览新旧框离得很远很远时用的槽。
   DS_PIECE, DS_PIECE2：正在下落的方块，跟踪方式和残影完全一样
              （见 piece_sync()）：小步移动就是一个并集矩形；而一次 HOLD
              交换可能把方块从井底甩回井顶，那就拆成两个矩形，而不是一个
              ~200 格的大框。
   DS_SCORE, DS_LEVEL, DS_LINES：三行数值，各自分开记。

   正因为彼此独立，重画才便宜；而一个矩形包含多少格，就等于它要卡住多长时间
   （见 game_hal.h 里关于批量写的说明；每帧只开一次写窗口，所以一帧里所有脏
   区域是当作一次事务画出去的）。要是把这些区域并成一个矩形，它就得从 NEXT
   条一直罩到井底——约 370 格。这里有三处拆分很关键，而第一处最关键，因为它
   每落一个方块都会发生：
     * 一个矩形是"缓冲区被画之前，标进它这个槽里的所有东西"的并集，而每个
       缓冲区是每三帧才被画一次。方块锁定时会在井底标出它所在的框，同一帧
       新方块出生又会在右上角标出 NEXT 条——如果它们在同一槽里，并集就是横跨
       整屏的约 300 格大框。它们分成不同的槽（DS_FIELD / DS_PANEL），这种事
       就永远不会发生。
     * 残影的擦除和重画共用同一个槽、取并集。若拆成两个槽，一次横向移动就要
       花两个约 40 格的矩形，而不是一个约 43 格的并集——而横向移动正是按住键
       时 DAS 连发每帧都要付的代价，也正是"重画慢一点就会被读成按键有延迟"的
       地方。只有当新旧框既不共享 x 也不共享 y 时，才把它们分开标（DS_GHOST2）：
       一次 HOLD 交换可能把残影挪到井的另一侧、高度也变了，这时它们的并集
       就是一个横跨半块场地的大斜框。
     * 三行数值分开标。它们虽然都在同一列 194 格里，但一次硬降只会动 SCORE，
       而消行除非真的升级了、否则不动 LEVEL——所以等级和行数两行不再跟着每
       一次分数变化一起重画。

   显示是三重缓冲的，每个显示帧只有一个缓冲区交给 M3，所以每一处改动都必须对
   三个缓冲区分别记住：矩形要并进全部三个缓冲区，等 M3 下次渲染到某个缓冲区
   时，那个缓冲区再清掉自己的槽。如果只共用一份拷贝，就会把同一个缓冲区重画
   三遍、而另外两个还留着老内容——那正好就是当初单缓冲时出现的残影。 */
#define DS_FIELD        0   /* 脏矩形槽 0：场地本身，落定方块和消行都标这里 */
#define DS_PANEL        1   /* 槽 1：NEXT 条——每出生一块、换一次 NEXT 都要重画 */
#define DS_HOLD         10  /* 槽 10：HOLD 小窗。它单独占一个槽，绝不和 NEXT 条
                               并成一个大矩形：两者都在顶部同一段行上，一并就
                               是横跨 270 多像素的大框，一次 HOLD 要白算好几千
                               个像素，那一帧就赶不上显示节拍了 */
#define DS_GHOST        2   /* 槽 2：落点预览（残影）新旧框的并集 */
#define DS_GHOST2       3   /* 槽 3：残影新旧框离得远时用的第二个槽 */
#define DS_SCORE        4   /* 槽 4：分数那一行 */
#define DS_LEVEL        5   /* 槽 5：等级那一行 */
#define DS_LINES        6   /* 槽 6：行数那一行 */
#define DS_PIECE        7   /* 槽 7：正在下落的方块 */
#define DS_PIECE2       8   /* 槽 8：下落方块一下跳得很远时用的第二个槽 */
#define DS_BANNER       9               /* 预先烤好的 GAME OVER 字样——单独
                                          占一个槽，这样闪烁的某个相位就永远
                                          不会把它并进（大得多的）场地矩形里
                                          把重画量撑爆 */
#define DIRTY_SLOTS     11   /* 总共 11 个脏矩形槽 */

/* 一帧最多往显存里写多少块（一块 = 显存的 128 字节）。显存写只能在垂直
   消隐那 1.4ms 里挤：写一块要走"打包 -> 突发 -> 降温"这一套，几十微秒，
   所以一帧写得下的块数是有限的。超出的块不会丢，只是顺延到下一帧（见主
   循环里的绘制顺序）。

   这个数是程序自己量出来的，不是拍脑袋定的：主循环会在绘制前后各读一次
   帧号，绘制期间帧号翻了 = 这一帧塞超了、多等了一个整帧，下次就少写一点；
   帧号没翻 = 还宽裕，下次就多写一点。硬件每个消隐能塞多少块只有实测才准。
   初值取个保守的中间值，几帧之内就会自己收敛。 */
static int paint_budget = 56;

/* 重画的先后顺序：玩家一眼就盯着的排前面。
   方块的新位置最先——硬降、HOLD 要的"立刻反应"就是它；然后是方块原来的
   位置（不擦会留残影）；再是场地和 HOLD 小窗（HOLD 是玩家按完键马上会看
   的地方，非 must 项里优先画，避免被预算拖到下一帧）；最后才是落点预览、
   横幅、NEXT 条和三行数值这些"晚一帧也看不出来"的东西。 */
static const signed char paint_order[DIRTY_SLOTS] = {
    DS_PIECE2, DS_PIECE, DS_FIELD, DS_HOLD, DS_GHOST2, DS_GHOST,
    DS_BANNER, DS_PANEL, DS_SCORE, DS_LEVEL, DS_LINES
};

typedef struct {   /* 记录「哪个区域需要重画」的结构 */
    int x1[DIRTY_SLOTS], y1[DIRTY_SLOTS];   /* 每个槽矩形的左上角坐标 */
    int x2[DIRTY_SLOTS], y2[DIRTY_SLOTS];   /* 每个槽矩形的右下角坐标 */
    int pend;                       /* 第 k 位为 1 表示第 k 个槽里有一个待重画的矩形 */
} Dirty;   /* 这个结构类型的名字叫 Dirty */
static Dirty dirty[3];   /* 三份拷贝，对应三个显示缓冲区，各自记要重画哪些区域 */

/* 把矩形 (x1,y1)-(x2,y2) 并进每个缓冲区（共三个）的第 k 个槽里。 */
static void mark_dirty_slot(int k, int x1, int y1, int x2, int y2)   /* 把一个矩形并进第 k 个槽，三个缓冲区都一起更新 */
{   /* 函数体开始 */
    int i;   /* 缓冲区循环用的下标 */
    if (k < 0 || k >= DIRTY_SLOTS) return;   /* 槽号不合法就直接返回 */
    if (x1 < 0) x1 = 0;   /* 把左边裁到屏幕内 */
    if (y1 < 0) y1 = 0;   /* 把上边裁到屏幕内 */
    if (x2 > HOR_PIXELS - 1) x2 = HOR_PIXELS - 1;   /* 把右边裁到屏幕内 */
    if (y2 > VER_PIXELS - 1) y2 = VER_PIXELS - 1;   /* 把下边裁到屏幕内 */
    if (x1 > x2 || y1 > y2) return;   /* 如果是空矩形就直接返回 */
    for (i = 0; i < 3; i++) {   /* 对三个显示缓冲区各处理一次 */
        if (!(dirty[i].pend & (1 << k))) {   /* 这个槽还空着，也就是第一次用 */
            dirty[i].x1[k] = x1; dirty[i].y1[k] = y1;   /* 直接存进矩形左上角 */
            dirty[i].x2[k] = x2; dirty[i].y2[k] = y2;   /* 存进矩形右下角 */
            dirty[i].pend |= 1 << k;   /* 标记这个槽有待重画的矩形 */
        } else {   /* 否则这个槽已经有矩形了 */
            if (x1 < dirty[i].x1[k]) dirty[i].x1[k] = x1;   /* 取并集：左边缘往更小取 */
            if (y1 < dirty[i].y1[k]) dirty[i].y1[k] = y1;   /* 上边缘也往更小取 */
            if (x2 > dirty[i].x2[k]) dirty[i].x2[k] = x2;   /* 右边缘往更大取 */
            if (y2 > dirty[i].y2[k]) dirty[i].y2[k] = y2;   /* 下边缘也往更大取 */
        }   /* 判断结束 */
    }   /* 缓冲区循环结束 */
}   /* 函数结束 */

static void mark_dirty(int x1, int y1, int x2, int y2)   /* 把矩形并进「场地」这个槽，是上面那个通用版的简写 */
{   /* 函数体开始 */
    mark_dirty_slot(DS_FIELD, x1, y1, x2, y2);   /* 就是调用上面的通用版本 */
}   /* 函数结束 */

/* 开工之前，先把「几乎压在一起」的矩形并成一个。
   硬降那一帧最典型：方块的新位置、锁定后场地要重画的那块、还有要擦掉的
   残影框——三块矩形盖的其实是同一小片地方。分开画就等于把同样的三四十
   块显存写三遍，而显存写只能挤在消隐窗口里，多写一遍就可能把这一帧顶出
   窗口、多等一整个 16.7ms，手感上就是"按下去之后晚一拍"。

   并起来内容完全一样（每个像素都是 game_pixel 现算的，不依赖缓冲区里原
   来的东西），所以只是省掉重复劳动。方块刚出生那几行、与落点预览隔得远
   的时候，这一下就把硬降那一帧的工作量砍掉三分之一。

   只并"重叠面积超过较小那个的一半"的，免得把两个天涯海角的矩形硬拉成
   一个横跨整屏的大框——那反而更贵。并进优先级高的那个槽，这样被并掉的
   内容不会因为槽位靠后被预算顺延。 */
static void merge_dirty(int b)   /* 把第 b 张缓冲里重叠得厉害的矩形并进优先级高的槽 */
{   /* 函数体开始 */
    int p, q, a, c;   /* 两个遍历下标，以及它们对应的槽号 */

    for (p = 0; p < DIRTY_SLOTS; p++) {   /* 按优先级从高到低走一遍 */
        a = paint_order[p];   /* 高优先级的槽号 */
        if (!(dirty[b].pend & (1 << a))) continue;   /* 这个槽没有待画的就跳过 */

        for (q = p + 1; q < DIRTY_SLOTS; q++) {   /* 再看所有比它次要的槽 */
            int ix1, iy1, ix2, iy2, inter, small;   /* 交集框、交集面积、较小那个的面积 */
            c = paint_order[q];   /* 次要的槽号 */
            if (!(dirty[b].pend & (1 << c))) continue;   /* 没有待画的就跳过 */

            ix1 = (dirty[b].x1[a] > dirty[b].x1[c]) ? dirty[b].x1[a] : dirty[b].x1[c];   /* 交集左边取大的 */
            iy1 = (dirty[b].y1[a] > dirty[b].y1[c]) ? dirty[b].y1[a] : dirty[b].y1[c];   /* 交集上边取大的 */
            ix2 = (dirty[b].x2[a] < dirty[b].x2[c]) ? dirty[b].x2[a] : dirty[b].x2[c];   /* 交集右边取小的 */
            iy2 = (dirty[b].y2[a] < dirty[b].y2[c]) ? dirty[b].y2[a] : dirty[b].y2[c];   /* 交集下边取小的 */
            if (ix1 > ix2 || iy1 > iy2) continue;   /* 根本不相交，不用管 */

            inter = (ix2 - ix1 + 1) * (iy2 - iy1 + 1);   /* 交集有多大 */
            small = (dirty[b].x2[a] - dirty[b].x1[a] + 1) *   /* 算 a 槽的面积 */
                    (dirty[b].y2[a] - dirty[b].y1[a] + 1);
            {   /* 顺带算出 c 槽的面积，取小的那个当分母 */
                int area_c = (dirty[b].x2[c] - dirty[b].x1[c] + 1) *
                             (dirty[b].y2[c] - dirty[b].y1[c] + 1);
                if (area_c < small) small = area_c;   /* 较小那个的面积 */
            }   /* 算面积结束 */
            if (inter * 2 < small) continue;   /* 重叠还不到一半，分开画更划算 */

            /* 并进高优先级的 a 槽，然后把 c 槽清掉 */
            if (dirty[b].x1[c] < dirty[b].x1[a]) dirty[b].x1[a] = dirty[b].x1[c];   /* 左边缘往小取 */
            if (dirty[b].y1[c] < dirty[b].y1[a]) dirty[b].y1[a] = dirty[b].y1[c];   /* 上边缘往小取 */
            if (dirty[b].x2[c] > dirty[b].x2[a]) dirty[b].x2[a] = dirty[b].x2[c];   /* 右边缘往大取 */
            if (dirty[b].y2[c] > dirty[b].y2[a]) dirty[b].y2[a] = dirty[b].y2[c];   /* 下边缘往大取 */
            dirty[b].pend &= ~(1 << c);   /* c 槽的内容已经被 a 槽盖住了 */
        }   /* 次要槽遍历结束 */
    }   /* 优先槽遍历结束 */
}   /* 函数结束 */

static int rnd7(void)   /* 产生 0 到 6 的随机数，用来决定下一个方块类型 */
{   /* 函数体开始 */
    rng_state = rng_state * 1103515245u + 12345u;   /* 线性同余随机数：先乘一个数再加一个数 */
    return (int)((rng_state >> 16) % 7u);   /* 取中间 16 位再对 7 取余，得到 0 到 6 */
}   /* 函数结束 */

