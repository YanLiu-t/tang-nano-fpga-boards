static int glyph_index(char c)   /* 把一个字符换成字库里的下标（0-9 是数字，10-35 是字母） */
{   /* 函数体开始 */
    if (c >= '0' && c <= '9') return c - '0';   /* 数字字符：下标就是它减去字符 0 */
    if (c >= 'A' && c <= 'Z') return 10 + (c - 'A');   /* 字母：下标从 10 开始往上排 */
    return -1;   /* 其它字符比如空格没有字形，返回 -1 */
}   /* 函数结束 */

/* 转成十进制、最高位在前；返回一共有几位数字。 */
static int fmt_u32(char *b, uint32_t v)   /* 把一个整数转成十进制字符串，写进 b，返回有几位 */
{   /* 函数体开始 */
    char t[10];   /* 临时倒着存放生成的各位数字 */
    int n = 0, i;   /* 已生成的位数，以及循环下标 */
    do { t[n++] = (char)('0' + (int)(v % 10u)); v /= 10u; } while (v && n < 10);   /* 每次取个位变成字符存起来，再除以 10，反复直到除尽 */
    for (i = 0; i < n; i++) b[i] = t[n - 1 - i];   /* 把这个倒着的数字正过来写进目标缓冲 */
    b[n] = 0;   /* 末尾补一个字符串结束符 0 */
    return n;   /* 返回一共有几位数字 */
}   /* 函数结束 */

/* 判断像素 (px,py) 是不是画在 (x0,y0)、共 n 个字符的字符串 s 里某个亮的点？
   sc = 整数放大倍数（1 或 2）。靠着几处便宜的提前返回，整屏重画才扛得住：
   每个字符的字格宽 6*sc、高 7*sc。 */
static int text_scan(int px, int py, int x0, int y0, const char *s, int n,   /* 判断像素 px,py 是否落在某段文字某个亮的字迹里 */
                     uint8_t col, int sc, uint8_t *out)   /* 续行：颜色、放大倍数、以及输出这个像素该用的颜色 */
{   /* 函数体开始 */
    int gx = px - x0, gy = py - y0;   /* 算出像素相对文字左上角的偏移 */
    int ci, bit, gi;   /* 第几个字符、字符里的第几列、字库下标 */
    if (gx < 0 || gy < 0 || gy >= 7 * sc) return 0;   /* 超出文字纵向范围就不算 */
    if (gx >= n * 6 * sc) return 0;   /* 超出文字横向范围也不算，每个字符宽 6 倍的放大倍数 */
    ci  = gx / (6 * sc);   /* 算出这是第几个字符 */
    bit = (gx % (6 * sc)) / sc;   /* 算出落在字符里的第几列，去掉放大倍数 */
    if (bit >= 5) return 0;   /* 字形只有 5 列宽，多出来的那一列是字符间距、是空白 */
    gi = glyph_index(s[ci]);   /* 查这个字符对应的字库下标 */
    if (gi < 0) return 0;   /* 不认识的字符就不画 */
    if (font5x7[gi][bit] & (1 << (gy / sc))) { *out = col; return 1; }   /* 查这一列对应行的点是否点亮，亮的话输出颜色并返回 1 */
    return 0;   /* 没点亮就返回 0 */
}   /* 函数结束 */

/* 这里一次性处理所有"烤好"的文字：五个固定标签，加上三个实时数值。

   数值只在它们发生变化时格式化一次（refresh_values()，从三个 mark_*_dirty()
   辅助函数里调用，开机时也调一次），而不是每个像素都格式化一遍：fmt_u32()
   每出一位数字就要做一次除法，而 game_pixel() 以前对数值行的每个像素都要跑
   它三遍，于是单单重画一次 SCORE 花在"把数字变成字符"上的时间，比把整帧推给
   面板的时间还多得多。这就是输入发卡背后最主要的那处停顿。

   先按每个元素所在的纵坐标区间分派：这些区间互不重叠，所以每个像素比一两次
   就能返回，而不用跑五趟字符串扫描。 */
static char sv_buf[12]; static int sv_n = 1;   /* 分数格式化后的字符串放这里，sv_n 是它有几位 */
static char lv_buf[12]; static int lv_n = 1;   /* 等级格式化后的字符串及位数 */
static char iv_buf[12]; static int iv_n = 1;   /* 行数格式化后的字符串及位数 */

static void refresh_values(void)   /* 把分数、等级、行数这三个数字重新格式化成字符串 */
{   /* 函数体开始 */
    sv_n = fmt_u32(sv_buf, score);   /* 格式化分数 */
    lv_n = fmt_u32(lv_buf, (uint32_t)level);   /* 格式化等级 */
    iv_n = fmt_u32(iv_buf, (uint32_t)lines_cleared);   /* 格式化行数 */
}   /* 函数结束 */

static int text_at(int x, int y, uint8_t *out)   /* 按纵坐标判断这个像素属于哪段文字，再去查它的字迹 */
{   /* 函数体开始 */
    if (y <  HLY          || y > IVY + 7 * 2 - 1) return 0;   /* 有效范围 44..171 */
    if (y <  HLY + 7)                                            /* HOLD / NEXT 标签所在的一带 */
        return text_scan(x, y, HLX, HLY, "HOLD", 4, IDX_TEXT, 1, out) ||   /* 查是不是 HOLD 标签的笔画 */
               text_scan(x, y, NLX, NLY, "NEXT", 4, IDX_TEXT, 1, out);   /* 或者 NEXT 标签的笔画 */
    if (y <  SLY) return 0;   /* 不在 SCORE 标签那一段就跳过 */
    if (y <  SLY + 7)   /* 落在 SCORE 标签这一行 */
        return text_scan(x, y, SLX, SLY, "SCORE", 5, IDX_TEXT, 1, out);   /* 查 SCORE 标签 */
    if (y <  SVY) return 0;   /* 不在分数数值那一段就跳过 */
    if (y <  SVY + 7 * 2)   /* 落在分数数值这一带，放大 2 倍所以高 14 像素 */
        return text_scan(x, y, SVX, SVY, sv_buf, sv_n, IDX_TEXT, 2, out);   /* 查分数数值 */
    if (y <  LLY) return 0;   /* 不在 LEVEL 标签那一段就跳过 */
    if (y <  LLY + 7)   /* 落在 LEVEL 标签这一行 */
        return text_scan(x, y, LLX, LLY, "LEVEL", 5, IDX_TEXT, 1, out);   /* 查 LEVEL 标签 */
    if (y <  LVY) return 0;   /* 不在等级数值那一段就跳过 */
    if (y <  LVY + 7 * 2)   /* 落在等级数值这一带 */
        return text_scan(x, y, LVX, LVY, lv_buf, lv_n, IDX_TEXT, 2, out);   /* 查等级数值 */
    if (y <  ILY) return 0;   /* 不在 LINES 标签那一段就跳过 */
    if (y <  ILY + 7)   /* 落在 LINES 标签这一行 */
        return text_scan(x, y, ILX, ILY, "LINES", 5, IDX_TEXT, 1, out);   /* 查 LINES 标签 */
    if (y <  IVY) return 0;   /* 不在行数数值那一段就跳过 */
    return text_scan(x, y, IVX, IVY, iv_buf, iv_n, IDX_TEXT, 2, out);   /* 查行数数值 */
}   /* 函数结束 */

/* 算出一个"已归一化"的方块在方框 (bx,by,bw,bh) 里居中放置时的原点。 */
static void piece_origin(const Cell *c, int bx, int by, int bw, int bh,   /* 算出一个方块在给定方框里居中放置时的原点像素坐标 */
                         int cw, int ch, int *ox, int *oy)   /* 续行：格子宽高，以及输出原点的两个参数 */
{   /* 函数体开始 */
    int i, mx = 0, my = 0;   /* 循环下标，以及方块自身外接框最右列、最下行 */
    for (i = 0; i < 4; i++) {   /* 四个格子逐个看 */
        if (c[i].x > mx) mx = c[i].x;   /* 记录最右的格子 */
        if (c[i].y > my) my = c[i].y;   /* 记录最下的格子 */
    }   /* 遍历结束 */
    *ox = bx + (bw - (mx + 1) * cw) / 2;   /* 水平居中：把剩下的空白左右平分 */
    *oy = by + (bh - (my + 1) * ch) / 2;   /* 垂直居中：把剩下的空白上下平分 */
}   /* 函数结束 */

/* HOLD 和 NEXT 的方块形状是"烤"进帧缓冲里的，而 game_pixel() 在每次重画的每
   个像素上都要跑一遍——所以它们的格子和居中原点只在队列或 HOLD 槽变化时在这
   里算一次，而不是每个像素都算。这样重画 NEXT 条才便宜。

   每个格子的绝对像素角点、以及方块自己的外接框也都缓存下来，于是逐像素判断
   就是几次整数比较，不做乘法、对那些没落在方块上的像素也不循环四个格子——
   而 NEXT 条上大部分像素都是这种情况。每出生一个新方块就要重画一次 NEXT。 */
static Cell hold_cells[4];   /* HOLD 槽里那个方块的 4 个格子坐标，预先算好缓存起来 */
static int  hold_ox, hold_oy;   /* HOLD 槽那个方块的左上角像素原点 */
static int  hold_cx[4], hold_cy[4];   /* HOLD 槽方块每个格子的绝对像素角点 */
static int  hold_bx1, hold_by1, hold_bx2, hold_by2;   /* HOLD 槽那个方块的像素外接框 */
static Cell next_cells[3][4];   /* 三个 NEXT 方块各自的 4 个格子坐标 */
static int  next_ox[3], next_oy[3];   /* 三个 NEXT 方块各自的原点 */
static int  next_cx[3][4], next_cy[3][4];   /* 三个 NEXT 方块各自的绝对像素角点 */
static int  next_bx1[3], next_by1[3], next_bx2[3], next_by2[3];   /* 三个 NEXT 方块各自的像素外接框 */

/* 计算一个方块四个格子的绝对角点，以及它的外接框。 */
static void cells_abs(const Cell *c, int ox, int oy, int cw, int ch,   /* 把「格子坐标」换算成「绝对像素角点」，顺便算出外接框 */
                      int *acx, int *acy, int *bx1, int *by1, int *bx2, int *by2)   /* 续行：输出角点和外接框的参数 */
{   /* 函数体开始 */
    int i, mx = 0, my = 0;   /* 循环下标，以及外接框最右列、最下行 */
    for (i = 0; i < 4; i++) {   /* 四个格子逐个处理 */
        acx[i] = ox + c[i].x * cw;   /* 这个格子的绝对 x 等于原点加上列号乘格宽 */
        acy[i] = oy + c[i].y * ch;   /* 绝对 y 等于原点加上行号乘格高 */
        if (c[i].x > mx) mx = c[i].x;   /* 更新最右的格子 */
        if (c[i].y > my) my = c[i].y;   /* 更新最下的格子 */
    }   /* 遍历结束 */
    *bx1 = ox;              *by1 = oy;   /* 外接框左上角就是原点 */
    *bx2 = ox + (mx + 1) * cw - 1;   /* 外接框右边缘等于原点加列数乘格宽再减一 */
    *by2 = oy + (my + 1) * ch - 1;   /* 下边缘同理 */
}   /* 函数结束 */

static void refresh_hold(void)   /* HOLD 槽内容变了：重新算好它的格子和位置缓存 */
{   /* 函数体开始 */
    if (hold_type < 0) return;   /* 槽是空的就不做 */
    piece_cells(hold_type, 0, hold_cells);   /* 取出 HOLD 方块的初始朝向格子 */
    piece_origin(hold_cells, HX0 + PB, HY0 + PB, HW - 2 * PB, HH - 2 * PB,   /* 算它在框里居中的位置，框要减去边框厚度 */
                 HCELL, HCELL, &hold_ox, &hold_oy);   /* 续行：格子边长和输出的原点 */
    cells_abs(hold_cells, hold_ox, hold_oy, HCELL, HCELL, hold_cx, hold_cy,   /* 换算成绝对像素角点 */
              &hold_bx1, &hold_by1, &hold_bx2, &hold_by2);   /* 并算出包围框 */
}   /* 函数结束 */

static void refresh_next(void)   /* NEXT 队列变了：重新算三个格子的缓存 */
{   /* 函数体开始 */
    int k;   /* 三个 NEXT 的下标 */
    for (k = 0; k < 3; k++) {   /* 三个 NEXT 依次处理 */
        if (nextq[k] < 0) continue;   /* 这个位置暂时没方块就跳过 */
        piece_cells(nextq[k], 0, next_cells[k]);   /* 取它的初始朝向格子 */
        piece_origin(next_cells[k], NBX0 + k * NSLOT, NY0 + PB, NSLOT,   /* 算它在自己那格里居中的原点 */
                     NH - 2 * PB, NCELL, NCELL, &next_ox[k], &next_oy[k]);   /* 续行：输出各个原点 */
        cells_abs(next_cells[k], next_ox[k], next_oy[k], NCELL, NCELL,   /* 换算成绝对像素角点 */
                  next_cx[k], next_cy[k],   /* 续行：输出角点 */
                  &next_bx1[k], &next_by1[k], &next_bx2[k], &next_by2[k]);   /* 以及算出包围框 */
    }   /* 循环结束 */
}   /* 函数结束 */

/* ------------------------------------------------------------------ */
/* 带高光的格子——方块上的一个小方块，也是唯一决定"一个方块像素该长什么样"  */
/* 的地方，所以正在下落的方块、落定的方块、HOLD 和 NEXT 都保证画得一模一样。 */
/*                                                                     */
/* 方块本体用方块自己的颜色，左上角沿对角线切出一块亮白色高光             */
/* （lx + ly < cw/2，也就是一个大约半个格子宽的角三角），这样这个小方块就    */
/* 像带镜面高光的倒角块；而这个半平面判断只要一次加法加一次比较——便宜到      */
/* 足以在每次重画的每个像素上都跑。调用方负责处理接缝：一个格子的最后一列    */
/* 和最后一行留给它后面的东西（场地，或者某个面板的内部），那正好就是把       */
/* 两个小方块隔开的那道 1 像素暗缝。                                       */
/* ------------------------------------------------------------------ */
static uint8_t cell_body(int lx, int ly, int cw, uint8_t base)   /* 画一个格子的像素：左上角是高光三角，其余用方块自己的颜色 */
{   /* 函数体开始 */
    return (lx + ly < (cw >> 1)) ? (uint8_t)IDX_HILITE : base;   /* 像素落在左上三角内就返回高光色，否则返回底色 */
}   /* 函数结束 */

/* 场地格子的"内框"。一个场地格子是 9 x 8，而场地自己那套网格规则（也就是
   game_pixel() 里空场地那种情况）会在它的第一列画一条 1 像素的线、在头两行
   各画一条 2 像素的线，于是留下一个 8 x 6 的内框。方块正好填满这个框、别的
   地方都不填，所以方块和它所占的背景格子一样大、正好落在那个格子内框的位置
   上，而且它的右边和下边与格子齐平。把两个小方块隔开的，正是格子自己的那圈
   网格带，也就是在空场地会画线的那同一个地方画线。

   1 像素 / 2 像素这种不对称是显示逼出来的、不是我们选的：读取引擎会把每一对
   源行流式读两遍，所以一条 1 像素的水平线会变成两条细线，只有 2 像素的带子
   才是一条实线。1 像素的竖线没有这个坑（见下面空场地那条规则）。
   参数是相对内框的坐标（列 0..7、行 0..5）。 */
static uint8_t cell_body_f(int lx, int ly, uint8_t base)   /* 场地格子的内框版本，同样在左上角画高光三角 */
{   /* 函数体开始 */
    return (lx + ly < 4) ? (uint8_t)IDX_HILITE : base;   /* 相对坐标和小于 4 的像素在左上三角内，给高光色 */
}   /* 函数结束 */

/* 判断 (x,y) 是否落在四个格子之一里面（这四个格子的绝对左上角是
   (acx[i],acy[i])，尺寸是 cw x ch）？如果在，*out 就收到那个格子本该有的、
   和 cell_body() 完全一样的颜色——这样 HOLD 或 NEXT 里的方块就得到和它所代表
   的方块一样的高光、一样在右下留出的暗缝。落在那些暗缝像素上时返回 0，调用
   方随后就把它们留成面板自己的背景色。 */
static int cell_shade_abs(const int *acx, const int *acy, int cw, int ch,   /* 判断像素是否落在某个格子里，是的话给出它该有的颜色 */
                          int x, int y, uint8_t base, uint8_t *out)   /* 续行：坐标、底色和输出颜色的参数 */
{   /* 函数体开始 */
    int i;   /* 格子的下标 */
    for (i = 0; i < 4; i++) {   /* 四个格子依次试 */
        if (x >= acx[i] && x < acx[i] + cw && y >= acy[i] && y < acy[i] + ch) {   /* 像素落在这个格子的范围内 */
            int lx = x - acx[i], ly = y - acy[i];   /* 算出它在格子内的相对坐标 */
            if (lx == cw - 1 || ly == ch - 1) return 0;   /* 最后一列或最后一行留着当暗缝，返回 0 让调用者用背景色 */
            *out = cell_body(lx, ly, cw, base);   /* 其它位置按格子规则给颜色 */
            return 1;   /* 命中就返回 1 */
        }   /* 判断结束 */
    }   /* 遍历结束 */
    return 0;   /* 不在任何格子里，返回 0 */
}   /* 函数结束 */

/* 场地格子 (c,r) 是不是残影（落点预览）的一部分？c/r 是场地的格子坐标，和
   game_pixel() 算出来的完全一样。残影的位置是 ghost_row 加上方块自己的格子
   偏移，列就是方块所在的列。 */
static int ghost_cell(int c, int r)   /* 判断场地第 c 列 r 行是不是残影占据的格子 */
{   /* 函数体开始 */
    int i;   /* 循环下标 */
    for (i = 0; i < 4; i++)   /* 残影的四个格子逐个比 */
        if (c == cur_x + cur_cells[i].x && r == ghost_row + cur_cells[i].y)   /* 这一格正好等于残影某个格子的位置 */
            return 1;   /* 是残影，返回 1 */
    return 0;   /* 不是，返回 0 */
}   /* 函数结束 */

/* ------------------------------------------------------------------ */
/* 帧缓冲在 (x,y) 这个像素上该是什么：背景、场地内部加边界、正在下落的     */
/* 方块、残影（落点预览）、HOLD 和 NEXT 面板（外框加方块形状），以及所有文字。 */
/*                                                                      */
/* 现在所有方块都是"烤"好的——包括正在下落的方块——因为面板画的矩形只能填 */
/* 一种纯色，而如今每个格子都带高光（见 cell_body()）。正是靠"烤"，才让    */
/* 正在下落的方块和一个落定方块能用同一次函数调用画出来，于是方块锁定那一刻 */
/* 屏幕上什么都看不出变化。                                              */
/*                                                                      */
/* 先后顺序很重要，而且就是当年那套精灵叠加的顺序：                       */
/* 下落方块 → 残影 → 落定方块 → 网格线。方块必须压过残影（当年精灵就画在  */
/* 残影之上，而且离落点只差一行的方块会压到残影的顶行），落定的格子又必须   */
/* 压过网格：方块用自己的颜色填满格子的内框，把格子自己的那圈网格带留给      */
/* 网格，于是它看起来就是一个完整的、做了倒角的小方块，尺寸正好和一个背景    */
/* 格子一样，而场地的线条还留在原处——一个方块，就是一个被画上颜色的背景格子。 */
/* ------------------------------------------------------------------ */
static uint8_t game_pixel(int x, int y)   /* 最核心的函数：给定一个像素坐标，算出它应该显示什么颜色 */
{   /* 函数体开始 */
    uint8_t col;   /* 临时存放查到的颜色 */

    /* ---- GAME OVER / PRESS TO CONTINUE 横幅（优先级最高）。只有"字"本身，
       红色（IDX_Z）：背后没有任何方框，所以不是亮字笔画的像素会直接落到井／
       面板／背景原本的东西上，横幅永远不会遮住画面。它会闪烁；go_shown 为 0
       时它就干脆不在。当前显示哪串字由 go_phase 决定：先显示 GAME OVER 那几
       个词，然后是同一带上的那句提示。 ---- */
    if (game_over && go_shown) {   /* 如果游戏结束、而且横幅此刻是亮着的 */
        if (go_phase == 0) {   /* 第一阶段显示 GAME OVER 字样 */
            if (x >= GO_X && x < GO_X + GO_W && y >= GO_Y && y < GO_Y + GO_H &&   /* 像素在 GAME OVER 横幅范围内 */
                text_scan(x, y, GO_X, GO_Y, GO_STR, GO_N, IDX_Z, GO_SC, &col))   /* 而且是某个亮着的字母笔画 */
                return col;   /* 就返回红色，也就是字形颜色 */
        } else if (x >= PC_X && x < PC_X + PC_W &&   /* 第二阶段：像素在提示框范围内 */
                   y >= PC_Y && y < PC_Y + PC_H &&   /* 纵向也在范围内 */
                   text_scan(x, y, PC_X, PC_Y, PC_STR, PC_N, IDX_Z, PC_SC, &col))   /* 并且是 PRESS TO CONTINUE 的亮笔画 */
            return col;   /* 返回红色 */
    }   /* 横幅判断结束 */

    /* ---- 场地内部 ---- */
    if (x >= X0 && x < X0 + COLS * CELLX && y >= Y0 && y < Y0 + ROWS * CELLY) {   /* 像素落在场地内部那 10 列 20 行里 */
        int gx = x - X0, gy = y - Y0;   /* 换成相对场地左上角的坐标 */
        /* 这里 gx 一定非负，所以这个除法会走编译器的无符号"魔术乘法"形式
           （一次乘法加一次移位），而不是更慢的、带符号修正的有符号除法。 */
        int c = (int)((unsigned)gx / (unsigned)CELLX);   /* 算它落在第几列，用无符号除法更快 */
        int lx = gx - c * CELLX;   /* 算它在格子内的横向偏移 */
        int r = gy >> 3;                       /* 右移 3 位等于除以 8（因为 CELLY 就是 8） */
        int ly = gy & 7;   /* 算它在格子内的纵向偏移，对 8 取余 */

        /* 正在下落的方块：四个"烤"好的格子，每个都和落定方块画出的那个带高光
           小方块一样（cell_body()）。在四个格子的循环前面先做一次便宜的包围框
           排除，这样整场重画（比如消行）时，每个像素才不用都去跑那个循环。 */
        if (running && !game_over &&   /* 游戏进行中、没结束，而且 */
            r >= cur_y && r <= cur_y + pmax_y &&   /* 这一行在方块的包围框内 */
            c >= cur_x && c <= cur_x + pmax_x) {   /* 这一列也在包围框内，这是便宜的筛选 */
            int i;   /* 循环下标 */
            for (i = 0; i < 4; i++) {   /* 方块的四个格子逐个看 */
                if (c == cur_x + cur_cells[i].x && r == cur_y + cur_cells[i].y) {   /* 正好是这个方块的某个格子 */
                    /* 方块本体直接胜出：就是落定方块画的那个带高光小方块
                       （cell_body()），这正是"锁定"这一步不花代价的原因。这里
                       不返回格子自己的那圈网格带，尽管方块确实是把那圈带留给
                       场地的网格：残影正落在方块要下到的那个行上，所以一个高的
                       方块会和残影最上面那几个格子共用它底部的格子，如果用网格
                       色去画那圈带，就会正好在方块盖住残影的位置把残影的框切开
                       ——缺口随方块高度时有时无。所以这圈带是"漏下去"的：如果
                       残影的框经过这个格子，就由残影给它上色；否则由下面的网格
                       规则把它画成场地自己的线（方块绝不可能和落定方块共用同一
                       个格子，所以没有别的东西会来争它）。 */
                    if (lx != 0 && ly > 1)   /* 不在格子最左列、也不在最上两行，也就是落在内框里 */
                        return cell_body_f(lx - 1, ly - 2,   /* 返回内框里的格子颜色 */
                                           (uint8_t)(PIECE_BASE + cur_type));   /* 底色等于调色板基址加上方块类型 */
                    break;   /* 找到就跳出循环 */
                }   /* 判断结束 */
            }   /* 遍历结束 */
        }   /* 筛选结束 */

        /* 残影：落点预览，就画成方块将要占据的那些格子，画法和"背景怎么画一个
           格子"一样——它把那个格子的网格带（第一列和头两行，也就是场地自己的
           1 像素／2 像素线）染成方块自己的颜色，而那个 8 x 6 的内框则保持成空
           场地时的样子（IDX_FIELD）。

           这就是为什么预览和背景格子一样大、形状也一样：它的线条压在网格线上
           ——以前它压在格子自己的最后一列／最后两行上，差了一两个像素，这才让
           预览看起来和它所在的场地不是同一种尺寸的砖块——而把形状里那些小方块
           隔开的，是格子的网格带、而不是方块边缘上的缝，位置正好就是场地的网格
           该画线的地方。形状自己那些格子的网格带没有一处是不染色的，所以预览
           内部也不会留下发丝般的缝。

           外框是这样收口的，而且它用到的每一圈带，都是场地自己的网格带（竖的
           1 像素／横的 2 像素），绝不用形状自己框里的像素，所以这个框既不会偏
           离网格，也不会让它的格子跟场地的格子不一样大：
             * 一个残影格子会给自己染上它自己的左列和头两行——那是它的左边缘、
               顶边缘，也是它和左边／上边的残影格子之间的分隔；
             * 右边缘是紧挨形状外侧那一格的左列，下边缘是往下一行那一格的头两
               行——这两条都由那个邻居来画，所以下面的判断会够到形状外一格、并
               且不要求那个邻居是空的。那个邻居反正也是场地的网格带；如果那里
               是落定方块，那个方块自己的网格带就是场地在那儿画的线，染色就
               正好落在它上面（残影在落定方块之前判断，所以染色胜出）。
           在地板那儿，下边缘根本不需要染色：井自己的底部边框就是那条线，最后
           一行的内框一直顶到它，和别的每一行完全一样。

           唯一一处别的东西画不了的地方，是台阶的内凹拐角：当形状在这个格子的
           左上方向延伸了一格、但不在正上、不在正左、也不在这里时，那个形状
           格子的右边缘（画在这个格子自己的左列里）和它的下边缘（画在这个格子
           自己的头两行里）会在这里相遇，而它们之间那个拐角会被留空——就是楼梯
           台阶以前会露出的那个小缺口。不管这两个边缘是由空的邻居还是落定的邻居
           带来，都把它填上：反正它们都带着这两条边缘；而当初正是"要求邻居是空
           的"这件事，在残影压到方块堆上的地方把填充关掉了——这就是那个缺口
           帧帧时有时无的原因。

           这些带的宽度用的是场地的、而不是它自己另定的样式：竖的 1 像素、横的
           2 像素，和背景网格完全一致（见下面空场地那条规则）。 */
        if (ghost_on &&   /* 如果此刻有残影，并且 */
            c >= cur_x && c <= cur_x + ghost_w + 1 &&   /* 这一列在残影框内，右边多算一格给边框 */
            r >= ghost_row && r <= ghost_row + ghost_h + 1) {   /* 这一行也在残影框内 */
            int g  = ghost_cell(c, r);          /* 这个格子是不是残影本身    */
            int gl = ghost_cell(c - 1, r);      /* 它左边那个格子是不是残影  */
            int gb = ghost_cell(c, r - 1);      /* 它上面那个格子是不是残影  */
            uint8_t ink = (uint8_t)(PIECE_BASE + cur_type);   /* 残影用的颜色就等于方块自己的颜色 */

            if (lx == 0 && (g || gl)) return ink;      /* 左边缘 + 与左边格子之间的分隔 */
            if (ly <= 1 && (g || gb)) return ink;      /* 顶边缘 + 与上面格子之间的分隔 */
            if (lx == 0 && ly <= 1 && ghost_cell(c - 1, r - 1)) return ink;   /* 补上台阶拐角那个缺角，保证残影边框闭合 */
            if (g && board[r][c] == 0) return IDX_FIELD;/* 残影占的格子内部那个内框 */
        }   /* 残影判断结束 */

        {   /* 开始画棋盘上已经落定的方块 */
            uint8_t v = board[r][c];   /* 取出这一格记录的值，0 表示空 */
            if (v) {   /* 如果这里是已经落定的方块 */
                /* 这个落定方块，逐字节都和下落方块"烤"进同一个格子的东西一样
                   （见 cell_body_f()）：格子的 8 x 6 内框里是它自己的颜色——正是
                   空场地用 IDX_FIELD 填满的那个框，所以方块正好和它所在的背景格子
                   一样大——而格子自己的那圈网格带（第一列／头两行）留给网格，于是
                   场地的线条还停在原处，两个相邻方块之间是场地自己的线、而不是
                   一道暗缺口。 */
                if (lx == 0 || ly <= 1) return IDX_GRID;   /* 格子的最左列和最上两行留给网格线 */
                return cell_body_f(lx - 1, ly - 2, v);   /* 内框用这个方块自己的颜色 */
            }   /* 落定方块判断结束 */
        }   /* 落定方块画完 */
        /* 空场地：画它的网格。列的规则是 1 像素（lx 为 0），行的规则是 2 像素
           （ly 为 0 和 1），这种不对称是显示管线逼出来的、不是我们选的。

           读取引擎会把每一对源行流式读两遍（top.v 里的 rd_copy），所以光栅的
           行序是 R0,R1,R0,R1,R2,R3,R2,R3……：一条源行会落在每隔一行的输出行上。
           因此一条 1 像素的水平线出来会变成"两条细线、中间夹着一行场地"——
           正是这套网格当初要从"一行、两条横线"问题里摆脱出来的那种样子。只有
           跨满整对（2p 和 2p+1 都用上）的带子才会填满连续四行输出、读起来才是
           一条实线，所以在这里一条"单一"水平线最细只能画成 2 像素。

           横向就没有这个坑——帧缓冲的每个字节只是显示成相邻的两个输出像素——
           所以 1 像素时列的规则已经读成一条干净的线，输出宽度只有 2 像素时的一
           半。用 1 像素 + 2 像素之后，每个格子的内部都正好是 8 x 6，空场地、
           落定方块（见 cell_body_f()）和残影完全一致，而井自己的边框也是同样宽度
           的一条网格线，所以不会有哪个格子跟别的格子大小不一样。 */
        if (lx == 0 || ly <= 1) return IDX_GRID;   /* 空格子：最左列和最上两行是网格线 */
        return IDX_FIELD;   /* 格子的其它部分用场地底色 */
    }   /* 场地内部画完 */
    /* ---- 井的外圈 ---- */
    /* 井的边缘是一条网格线，而不是在第一批格子"外面"硬加上去的一圈亮边。左边缘
       和上边缘其实就是最外面那些格子自己的网格带，由上面那条规则画出来；只剩
       右边缘和下边缘要单独画，两者都正好一条网格线那么厚——右边 1 像素、底边
       2 像素，就是场地自己的 1 像素／2 像素宽度。以前这里压着一圈 IDX_BORDER，
       紧挨在第一批格子网格带的外面，结果那些边缘线比每条内部线都粗一倍（左边
       和上边是圈+带叠起来），而且用了一种内部线不用的亮色，这才让外围那些格子
       ——以及（因为它底边是亮的那条）最后一行——看起来比其余背景要小。 */
    if (x == X0 + COLS * CELLX && y >= Y0 && y < Y0 + ROWS * CELLY) {   /* 这是场地的右边缘那条竖线 */
        /* 只要残影最外那列就是场地的最后一列，这条线就正是残影右边缘所在的那条
           线：边缘规则会把一个形状格子的右边缘画在下一格的第一列里，而再往外
           一格，就只剩这道边框了。要是把它留成边框自己的网格色，残影的框就会
           贴着墙被切断，所以把形状真正够到的那一段线——也仅那一段——染成残影的
           颜色。位置一点没动：还是同一条 1 像素的线、还在原处，所以没有哪个格子
           改变尺寸。墙右边没有格子，所以这里把内部拐角规则镜像过来：最后一列里
           往上偏一行的残影格子，它的右边缘横穿这条线、下边缘横穿下一行的头两行，
           这个拐角只有当它下面那格也是残影时才闭合。把这个拐角也带到墙上来。 */
        int rr = (y - Y0) >> 3;   /* 算这个像素落在第几行 */
        if (ghost_on && (ghost_cell(COLS - 1, rr) ||   /* 如果残影贴在最右一列 */
                         (((y - Y0) & 7) <= 1 && rr >= 1 &&   /* 或者上一行最右格是残影、而且这里正好在它的下边缘 */
                          ghost_cell(COLS - 1, rr - 1))))   /* 合起来就是残影框右下角的外沿 */
            return (uint8_t)(PIECE_BASE + cur_type);   /* 就用方块颜色，让残影的边框连过去 */
        return IDX_GRID;   /* 否则就是普通的网格线 */
    }   /* 右边缘处理结束 */
    if (y >= Y0 + ROWS * CELLY && y < Y0 + ROWS * CELLY + 2 &&   /* 这是场地底边缘那条横线，2 像素高 */
        x >= X0 && x <= X0 + COLS * CELLX) {   /* 续行的条件：x 在场地横向范围内 */
        /* 而这条就是残影压到地板上时下边缘会用的那条线——2 像素、场地自己的横向
           宽度，和它在场地内再往下一行本该有的完全一样。越过最后一列的那个像素
           算作那一列的拐角，也就是它右边缘和下边缘相交的地方，框必须在这里闭合。
           同样的接缝还会出现在一个残影格子的下边缘、和它左边那列的右边缘之间，
           缺一格——地板是唯一一处那条边不被画出来的地方，所以在这里补上。 */
        int bc = (int)((unsigned)(x - X0) / (unsigned)CELLX);   /* 算这个像素在第几列 */
        int lxb = (x - X0) - bc * CELLX;   /* 算它在格子内的横向偏移 */
        if (bc >= COLS) {   /* 如果落在最后一列之外，也就是右下角那个像素 */
            if (ghost_on && ghost_cell(COLS - 1, ROWS - 1))   /* 而残影正好停在最底一行最后一列 */
                return (uint8_t)(PIECE_BASE + cur_type);   /* 用方块颜色把边框角补上 */
            return IDX_GRID;   /* 否则是普通网格线 */
        }   /* 这一小段判断结束 */
        if (ghost_on && (ghost_cell(bc, ROWS - 1) ||   /* 如果这一列最底格是残影 */
                         (lxb == 0 && bc >= 1 && ghost_cell(bc - 1, ROWS - 1))))   /* 或者左边一格最底是残影、且这里在它的右边缘 */
            return (uint8_t)(PIECE_BASE + cur_type);   /* 用方块颜色，把边框连上 */
        return IDX_GRID;   /* 否则是普通网格线 */
    }   /* 底边缘处理结束 */

    /* ---- HOLD 小窗 ---- */
    if (x >= HX0 && x < HX0 + HW && y >= HY0 && y < HY0 + HH) {   /* 像素落在 HOLD 小窗里 */
        if (x < HX0 + PB || x >= HX0 + HW - PB ||   /* 如果落在小窗的纵向边框带上 */
            y < HY0 + PB || y >= HY0 + HH - PB)   /* 或者横向边框带上 */
            return IDX_BORDER;   /* 就画成边框色 */
        if (running && hold_type >= 0 &&   /* 游戏进行中、而且 HOLD 槽里有方块 */
            x >= hold_bx1 && x <= hold_bx2 &&   /* 像素在方块外接框横向范围内 */
            y >= hold_by1 && y <= hold_by2 &&   /* 纵向也在 */
            cell_shade_abs(hold_cx, hold_cy, HCELL, HCELL, x, y,   /* 并且命中它的某个格子 */
                           (uint8_t)(PIECE_BASE + hold_type), &col))   /* 用 HOLD 方块自己的颜色 */
            return col;   /* 返回命中的颜色 */
        return IDX_PANEL_BG;   /* 否则就是面板内部底色 */
    }   /* HOLD 小窗处理结束 */

    /* ---- NEXT 条（三个方块并排）---- */
    if (x >= NX0 && x < NX0 + NW && y >= NY0 && y < NY0 + NH) {   /* 像素落在 NEXT 条里 */
        int k;   /* 三个 NEXT 的下标 */
        if (x < NX0 + PB || x >= NX0 + NW - PB ||   /* 如果落在 NEXT 条的外框上 */
            y < NY0 + PB || y >= NY0 + NH - PB)   /* 纵向也在边框带上 */
            return IDX_BORDER;   /* 画成外框色 */
        if (running) {   /* 游戏进行中 */
            for (k = 0; k < 3; k++) {   /* 三个 NEXT 方块依次看 */
                if (nextq[k] < 0) continue;   /* 这个位置空着就跳过 */
                if (x >= next_bx1[k] && x <= next_bx2[k] &&   /* 像素在第 k 个方块外接框横向范围内 */
                    y >= next_by1[k] && y <= next_by2[k] &&   /* 纵向也在 */
                    cell_shade_abs(next_cx[k], next_cy[k], NCELL, NCELL, x, y,   /* 并且命中它的某个格子 */
                                   (uint8_t)(PIECE_BASE + nextq[k]), &col))   /* 用这个方块自己的颜色 */
                    return col;   /* 返回颜色 */
            }   /* 循环结束 */
        }   /* 判断结束 */
        return IDX_PANEL_BG;   /* 否则是 NEXT 条内部底色 */
    }   /* NEXT 条处理结束 */

    /* ---- 各种标签 + 实时数值 ---- */
    if (text_at(x, y, &col)) return col;   /* 如果这个像素是某段文字的字迹，就返回它的颜色 */

    /* ---- 井的围边 ---- */
    /* 井就是那片深色的游戏场地，在它自己的边缘线外面，它围着一圈扁平的蛋壳白
       边，和各个面板围边的方式一样（IDX_BORDER）。这圈边是它自己独立的一条带，
       就在井本来就留着的空档里：它从井的边缘线结束的地方开始——右边缘线外 1 像素、
       底边缘线外 2 像素（也就是场地自己的 1 像素／2 像素宽度）、第一列和第一行
       外 2 像素——然后整圈都是 BORDER 那么厚，拐角也算在内。

       它和井画出的任何东西（包括残影）都不共用任何一个像素，而这正是关键所在。
       以前这里是一圈压在井边缘上的边框，那它只要碰上残影自己的边缘就得让位
       （或者把残影裁掉）——边框就被啃掉一块，有一部分被残影的颜色占了。挪到
       边缘之外的自己那条带上之后，井内部没有任何东西能碰到这些像素，所以边框
       永远是完整的，残影也是：残影的虚线一直跑到井的边缘线，而圆环就在它外面
       继续画下去、丝毫不受影响。

       它放在最后判断，在标签之后，所以它不会盖住任何一段文字，而且它不改变
       井、或任何一个格子的任何坐标。 */
    if (x >= X0 - BORDER && x <= X0 + COLS * CELLX + BORDER &&   /* 像素在场地外圈那圈亮边范围内 */
        y >= Y0 - BORDER && y <= Y0 + ROWS * CELLY + 1 + BORDER &&   /* 纵向也在 */
        (x < X0 || x > X0 + COLS * CELLX ||   /* 并且在场地边缘线之外 */
         y < Y0 || y > Y0 + ROWS * CELLY + 1))   /* 横向也在外面 */
        return IDX_BORDER;   /* 画成外框色 */

    return IDX_BG0;                    /* 剩下的都用一种扁平的背景色 */
}   /* 函数结束 */

