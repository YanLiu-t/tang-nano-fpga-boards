/* ------------------------------------------------------------------ */
/* Background synthesis (integer math only)                            */
/* ------------------------------------------------------------------ */
/* triangle wave: 0..amp, period p */
static int32_t tri(int32_t x, int32_t p, int32_t amp)
{
    int32_t h = p / 2;
    int32_t m = x % p;
    int32_t t = (m < h) ? m : (p - m);
    return (t * amp) / h;
}

/* The two mountain ridges depend ONLY on x, yet the old bg_pixel() evaluated
   four tri() calls - four software divisions plus four modulo ops - for EVERY
   pixel of EVERY row (640*480 = 307200 times). The Cortex-M3 has no divide
   instruction, so that single loop dominated compose_block() and capped the
   game loop at roughly 12 blocks per vblank write window - which is exactly
   why both the ball and the paddle felt slow: the physics advances once per
   completed render, and a render only got ~12 blocks per frame through the
   write channel. Both ridge sums are tabulated once at startup now, so the
   per-pixel cost collapses to two byte loads. The sums are 0..70 and 0..62,
   so int8_t is ample.
   NOTE: the three hash-based per-pixel textures (grass-edge brightness,
   ground speckle, sky star field) are still REMOVED - re-adding any of them
   brings back the "electric interference" speckle. */
static int8_t ridge_near[HOR_PIXELS];   /* tri(x,150,60) + tri(x,47,10) */
static int8_t ridge_far [HOR_PIXELS];   /* tri(x,220,50) + tri(x,73,12) */

static void bg_init(void)
{
    int32_t x;
    for (x = 0; x < HOR_PIXELS; x++) {
        ridge_near[x] = (int8_t)(tri(x, 150, 60) + tri(x, 47, 10));
        ridge_far [x] = (int8_t)(tri(x, 220, 50) + tri(x, 73, 12));
    }
}

/* The sky gradient and the jungle-ground shading depend ONLY on y as well, and
   used to cost three more divisions per PIXEL. They are computed once per ROW
   here (bg_row() is called at the top of compose_block), and bg_pixel() then
   just reads the cached colour. */
static int32_t  bg_row_y = -1;
static int      row_ground;      /* 1 = this row is at/below GROUND_Y */
static int      row_grass;       /* 1 = grass-edge band               */
static uint32_t row_ground_rgb;  /* shaded jungle ground              */
static uint32_t row_sky_rgb;     /* sunset gradient                   */

#define COL_GRASS  (((uint32_t)(180u >> 3) << 16) | (180u << 8) | 0x28u)

static void bg_row(int32_t y)
{
    if (y == bg_row_y)
        return;
    bg_row_y = y;

    if (y >= GROUND_Y) {
        row_ground = 1;
        row_grass  = (y < GROUND_Y + 6);
        if (!row_grass) {
            int32_t d = y - GROUND_Y - 6;
            int32_t g = 100 - d;
            if (g < 32) g = 32;
            row_ground_rgb = (0x0Fu << 16) | ((uint32_t)g << 8) | 0x16u;
        }
    } else {
        uint32_t r, g, b;
        row_ground = 0;
        row_grass  = 0;
        r = 10u + (uint32_t)(190 * y) / 400u;
        g = 8u  + (uint32_t)(70 * y) / 400u;
        b = 50u - (uint32_t)(10 * y) / 400u;
        if (y > 300) b += (uint32_t)(y - 300) / 4u;
        row_sky_rgb = (r << 16) | (g << 8) | b;
    }
}

static uint32_t bg_pixel(int32_t x, int32_t y)
{
    if (row_ground)
        return row_grass ? COL_GRASS : row_ground_rgb;

    /* sky: two mountain ridges in front of the cached sunset gradient */
    {
        int32_t yr2 = 300 + ridge_near[x];   /* near ridge */
        int32_t yr1 = 230 + ridge_far [x];   /* far  ridge */
        int32_t d;
        if (y >= yr2) {
            d = y - yr2; if (d > 14) d = 14;
            return ((uint32_t)(18 - (d >> 1)) << 16) |
                   ((uint32_t)(12 - (d >> 2)) << 8) | (uint32_t)(32 - (d >> 1));
        }
        if (y >= yr1) {
            d = y - yr1; if (d > 20) d = 20;
            return ((uint32_t)(35 - d) << 16) |
                   ((uint32_t)(20 - (d >> 1)) << 8) | (uint32_t)(55 - d);
        }
        return row_sky_rgb;
    }
}

/* ------------------------------------------------------------------ */
/* Foreground objects BAKED INTO the framebuffer (digits + diagnostics). */
/* The ball and the paddles are NOT here any more: they are overlaid by the
   fabric (top.v spr_px) from their position registers, so they must stay out
   of the memory image or they would be left behind as ghosts when they move. */
/* Returns 1 and *rgb when an object covers (x,y), else 0.             */
/* ------------------------------------------------------------------ */
static int32_t obj_pixel(int32_t x, int32_t y, uint32_t *rgb)
{
    /* score digits */
    if (y >= DIGIT_Y && y < DIGIT_Y + DIGIT_H) {
        int32_t d;
        for (d = 0; d < 4; d++) {
            int32_t xoff = digit_x[d];
            if (x >= xoff && x < xoff + DIGIT_W) {
                int32_t val = (d == 0) ? s1 / 10 : (d == 1) ? s1 % 10 :
                              (d == 2) ? s2 / 10 : s2 % 10;
                int32_t row = (y - DIGIT_Y) / DIGIT_SCALE;
                int32_t col = (x - xoff) / DIGIT_SCALE;
                if (row < 5 && col < 3 &&
                    (font5x3[val] & (1u << (row + col * 5)))) {
                    *rgb = digit_dim ? COL_DIGIT_DIM : COL_DIGIT;
                    return 1;
                }
            }
        }
    }

    return 0;
}

/* ------------------------------------------------------------------ */
/* Compose one 128-byte block of row `y` (block column `kc`, 0..14)    */
/* Byte g (global) -> pixel x = g/3, channel = g%3 (0=R,1=G,2=B).      */
/* ------------------------------------------------------------------ */
static uint8_t blk_buf[128];

/* Memory byte order per pixel.
   top.v's pixel mux emits {grp[79:72], grp[87:80], grp[95:88]}, i.e. the
   first three bytes of the 32-bit word REVERSED; and the SVO stack binds
   bits[23:16] to the BLUE lane (proved by the test pattern: 0xFF0000 was
   displayed BLUE and yellow/cyan came out swapped). Reversal + BGR lane
   order cancel out, so a memory byte stream of plain [R,G,B] is displayed as
   [R,G,B]. The memory must therefore hold [R,G,B]: channel 0 -> >>16,
   1 -> >>8, 2 -> >>0. The previous { 8, 0, 16 } stored [G,B,R] and rotated
   every colour by one channel (cyan paddle -> yellow-green, yellow score ->
   violet) - that is the "colour stain", not a memory fault. */
static const uint8_t ch_shift[3] = { 16, 8, 0 };

static void compose_block(int32_t y, int32_t kc)
{
    int32_t g0 = kc * 128;
    int32_t x = g0 / 3;
    int32_t c = g0 % 3;
    int32_t j;
    uint32_t rgb = 0;

    bg_row(y);          /* cache the y-only background colours for this row */

    for (j = 0; j < 128; j++) {
        /* 128 bytes is not a whole number of pixels (128 = 42*3 + 2), so a
           block can start in the middle of a pixel (c = g0 % 3 != 0). In that
           case the first byte(s) belong to a pixel whose R was already written
           by the previous block - we must still evaluate it here, otherwise
           rgb stays 0 and the pixel's remaining channels render as 0 (dark
           specks at every block boundary). */
        if (c == 0 || j == 0) {
            /* new pixel: evaluate object first, else background */
            if (!obj_pixel(x, y, &rgb))
                rgb = bg_pixel(x, y);
        }
        blk_buf[j] = (uint8_t)((rgb >> ch_shift[c]) & 0xFFu);
        if (++c == 3) { c = 0; x++; }
    }
}

static void write_block(int32_t y, int32_t kc)
{
    compose_block(y, kc);
    fb_block((uint32_t)(y * BLOCKS_PER_ROW + kc), blk_buf);
}

/* Rewrite every block touched by rect (x1,y1)-(x2,y2) inclusive. */
static void fill_rect(int32_t x1, int32_t y1, int32_t x2, int32_t y2)
{
    int32_t kl, kr, k, y;

    if (x1 < 0) x1 = 0;
    if (y1 < 0) y1 = 0;
    if (x2 > HOR_PIXELS - 1) x2 = HOR_PIXELS - 1;
    if (y2 > VER_PIXELS - 1) y2 = VER_PIXELS - 1;
    if (x1 > x2 || y1 > y2) return;

    kl = (x1 * 3) >> 7;
    kr = ((x2 * 3 + 2) >> 7);
    if (kr > BLOCKS_PER_ROW - 1) kr = BLOCKS_PER_ROW - 1;

    for (y = y1; y <= y2; y++)
        for (k = kl; k <= kr; k++)
            write_block(y, k);
}

/* Full initial scene: compose every block (background + objects). */
static void draw_full_scene(void)
{
    int32_t y, k;
    for (y = 0; y < VER_PIXELS; y++)
        for (k = 0; k < BLOCKS_PER_ROW; k++)
            write_block(y, k);
}

