/*
 * Color Pong for Tang Nano 4K (GW1NSR-4C) - PSRAM RGB888 framebuffer.
 *
 * 架构:
 *   Cortex-M3 以 128 字节 (32 词) 块为单位, 经 APB2 桥把合成好的 RGB888
 *   像素写入板载 HyperRAM 帧缓冲 (640x480, 每行 1920 字节 = 15 块);
 *   fabric 读引擎持续把整帧经 HDMI 输出 (640x480@60 全彩)。
 *
 * 渲染模型 (与旧单色版相同的 "compose" 思想):
 *   每个块的内容 = compose(背景 + 当前物体), 擦除 = 用当前状态重写旧区域,
 *   因此显示端永远读不到 "擦了一半" 的中间态。
 *   背景是静态的魂斗罗风格场景: 日落渐变天空 + 星星 + 两层山峦剪影 +
 *   丛林地面 + 中场虚线, 全部整数运算按坐标即时合成。
 *   物体 (按优先级): 球 > 比分数字 > 球拍 > 背景。
 *
 * 小球与两块挡板改由 fabric 在像素通路上实时叠加 (top.v 的 spr_px): M3 每帧
 * 只写 4 个位置寄存器 (0x40/0x44/0x48/0x4C), 不再往帧缓冲里画它们。
 * 物体的运动因此完全脱离 HyperRAM 写通道 (每帧只有垂直消隐期一个写窗口,
 * 每个窗口只能推出几十个 128 字节块) 的限制, 可以做到真正的 60fps 平滑运动,
 * 速度也能自由提高而不再拖慢画面。
 * 帧缓冲里只剩静态内容, 每帧只重写 "脏区域" 的块:
 *   数字: 仅比分变化 / 终局闪烁时
 *   诊断: 仅状态翻转时
 *
 * 控制: KEY1 上移 / KEY2 下移 / KEY3 重置
 * 规则: 先得 15 分者胜, 球停止, 比分闪烁
 */
#include "gw1ns4c.h"
#include "delay.h"

