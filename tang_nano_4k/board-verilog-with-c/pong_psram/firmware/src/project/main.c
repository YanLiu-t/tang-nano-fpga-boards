/* ------------------------------------------------------------------ */
/* APB2 register map (matches apb_pong_reg.v)                          */
/* ------------------------------------------------------------------ */
#define PONG_APB_BASE   (APB2MASTER1_BASE)   /* 0x40002400 */

#define REG_KEY         0x04    /* RO keys (pressed = 0)                */
#define REG_HP          0x08    /* RO bit0 = HyperRAM init_calib done   */
#define REG_FRAME       0x0C    /* RO [7:0] display frame counter       */
#define REG_FB_BLK      0x24    /* WO [12:0] 128-byte block index       */
#define REG_FB_DATA     0x28    /* WO framebuffer word (toggles req)    */
#define REG_FB_STATUS   0x2C    /* RO bit0 = ack sync                   */
#define REG_BUF_SWAP    0x30    /* WO toggles: request framebuffer flip */
#define REG_BUF_DISP    0x34    /* RO bit0 = displayed framebuffer 0/1  */
#define REG_FB_READY    0x38    /* WO toggles: first whole frame is up  */
#define REG_P1_Y        0x40    /* WO [9:0] P1 paddle top row (overlay) */
#define REG_P2_Y        0x44    /* WO [9:0] P2 paddle top row (overlay) */
#define REG_BALL_X      0x48    /* WO [9:0] ball centre x     (overlay) */
#define REG_BALL_Y      0x4C    /* WO [9:0] ball centre y     (overlay) */

/* Bit map measured on hardware with the eight-square monitor drawn by
   obj_pixel() (square 1 = bit 0, numbered from the left). The two direction
   keys were still inverted on the bench - the key the user calls "up" moved the
   paddle DOWN - so the pair is SWAPPED relative to the first measurement: bit 1
   now drives the paddle UP, bit 2 drives it DOWN. If the directions ever come
   out reversed again, this pair is the only thing to flip.
   KEY_RESET (bit 0) has not been measured yet - press the reset key and read
   which square turns red, then narrow this mask the same way. */
#define KEY_UP          ((1u << 1))
#define KEY_DOWN        ((1u << 2))
#define KEY_RESET       ((1u << 0))   /* unmeasured */
#define KEY_PRESSED(k)  (((apb_read(REG_KEY) & (k)) != (k)))

